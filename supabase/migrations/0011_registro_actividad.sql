-- Nombre de una empresa solo para quien puede verla (evita exponer nombres ajenos).
create or replace function public.nombre_empresa_visible(p_empresa uuid)
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select e.nombre from public.empresas e
   where e.id = p_empresa
     and (public.es_admin_plataforma() or public.es_miembro(p_empresa));
$$;

create or replace view public.v_registros
with (security_invoker = true) as
select
  r.id,
  r.creado_en,
  r.tipo,
  r.nivel,
  r.evento,
  r.mensaje,
  r.id_usuario,
  coalesce(u.nombre, r.correo) as usuario,
  r.correo,
  r.id_empresa,
  public.nombre_empresa_visible(r.id_empresa) as empresa,
  r.tabla,
  r.id_registro,
  host(r.ip) as ip,
  r.dispositivo,
  r.agente,
  nullif(concat_ws(', ', r.ciudad, r.pais), '') as ubicacion,
  r.ruta,
  r.metodo,
  r.referente,
  r.entorno,
  r.datos
from public.registros r
left join public.usuarios u on u.id = r.id_usuario;

grant select on public.v_registros to authenticated;

-- -----------------------------------------------------------------------------
-- 5. Limpieza (manual o con pg_cron)
-- -----------------------------------------------------------------------------

-- Borra visitas viejas (las más numerosas) y el resto pasado un plazo mayor.
-- Ejemplo con pg_cron (si se habilita la extensión):
--   select cron.schedule('limpiar-registros', '0 4 * * *', 'select public.limpiar_registros()');
create or replace function public.limpiar_registros(p_dias_visitas int default 180, p_dias_resto int default 730)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_borrados bigint;
begin
  if auth.uid() is not null and not public.es_admin_plataforma() then
    raise exception 'Solo el administrador de la plataforma puede limpiar el registro.';
  end if;
  delete from public.registros
   where (tipo = 'visita' and creado_en < now() - make_interval(days => greatest(p_dias_visitas, 30)))
      or (creado_en < now() - make_interval(days => greatest(p_dias_resto, 90)));
  get diagnostics v_borrados = row_count;
  return v_borrados;
end;
$$;

revoke execute on function public.limpiar_registros(int, int) from public, anon;
grant execute on function public.limpiar_registros(int, int) to authenticated;

commit;
