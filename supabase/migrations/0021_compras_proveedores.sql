create index if not exists proveedores_creado_por_idx on public.proveedores (creado_por);
create unique index if not exists proveedores_rtn_key on public.proveedores (id_empresa, rtn) where rtn is not null;

select pg_temp.restriccion_0021('public.proveedores', 'proveedores_nombre_check',
  $$check (btrim(nombre) <> '' and char_length(nombre) <= 160)$$);
select pg_temp.restriccion_0021('public.proveedores', 'proveedores_rtn_check',
  $$check (rtn is null or rtn ~ '^\d{14}$')$$);
select pg_temp.restriccion_0021('public.proveedores', 'proveedores_textos_check',
  $$check ((telefono is null or char_length(telefono) <= 30) and (correo is null or char_length(correo) <= 120)
           and (direccion is null or char_length(direccion) <= 200) and (contacto is null or char_length(contacto) <= 120)
           and (notas is null or char_length(notas) <= 500))$$);
select pg_temp.restriccion_0021('public.proveedores', 'proveedores_dias_check',
  $$check (dias_credito between 0 and 365)$$);

create or replace function public.tg_normalizar_proveedor()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if tg_op = 'UPDATE' and new.id_empresa <> old.id_empresa then
    raise exception 'No se puede cambiar la empresa de un proveedor.';
  end if;
  new.nombre := upper(regexp_replace(btrim(new.nombre), '\s+', ' ', 'g'));
  new.rtn := nullif(regexp_replace(coalesce(new.rtn, ''), '\D', '', 'g'), '');
  new.telefono := nullif(btrim(new.telefono), '');
  new.correo := nullif(lower(btrim(new.correo)), '');
  new.direccion := nullif(btrim(new.direccion), '');
  new.contacto := nullif(btrim(new.contacto), '');
  new.notas := nullif(btrim(new.notas), '');
  return new;
end;
$$;

create or replace trigger a_normalizar
  before insert or update on public.proveedores
  for each row execute function public.tg_normalizar_proveedor();

