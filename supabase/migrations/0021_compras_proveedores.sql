-- 4. Cuentas por pagar
-- -----------------------------------------------------------------------------

-- Una fila por compra al crédito vigente, con lo que queda por pagar.
create or replace view public.v_cuentas_pagar with (security_invoker = true) as
with base as (
  select c.id, c.id_empresa, c.numero, c.documento, c.fecha, c.vence, c.id_proveedor, c.proveedor_nombre, c.total,
         coalesce((select sum(a.monto) from public.pagos_proveedores_aplicaciones a
                     join public.pagos_proveedores p on p.id = a.id_pago
                    where a.id_compra = c.id and p.estado = 'emitido'), 0) as pagado,
         (now() at time zone 'America/Tegucigalpa')::date as hoy
    from public.compras c
   where c.condicion = 'credito' and c.estado = 'emitido'
)
select b.id, b.id_empresa, b.numero, b.documento, b.fecha, b.vence, b.id_proveedor, b.proveedor_nombre,
       b.total, b.pagado,
       b.total - b.pagado as pendiente,
       greatest(b.hoy - b.vence, 0) as dias_vencida,
       case when b.total - b.pagado <= 0 then 'pagada'
            when b.hoy > b.vence then 'vencida'
            when b.vence - b.hoy <= 7 then 'por_vencer'
            else 'al_dia' end as estado
  from base b;

-- -----------------------------------------------------------------------------
-- 5. Registrar y anular compras
-- -----------------------------------------------------------------------------

/*
  p_compra: {
    tipo: inventario | gasto, id_proveedor, documento?, cai?, fecha (AAAA-MM-DD),
    condicion: contado | credito, vence? (crédito; si falta: fecha + plazo del proveedor),
    forma_pago? (contado), referencia?, de_caja? (efectivo desde la caja abierta),
    isv? (el de la factura del proveedor; si falta, 15 % de lo gravado), notas?,
    lineas: inventario [{ id_producto, cantidad, costo, exento? }]
            gasto      [{ descripcion, monto, exento? }]
  }
  Costos y montos sin ISV. Devuelve el id de la compra.
*/
create or replace function public.registrar_compra(p_empresa uuid, p_compra jsonb)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_proveedor public.proveedores;
  v_producto public.productos;
  v_tipo text := coalesce(p_compra ->> 'tipo', 'inventario');
  v_condicion text := coalesce(p_compra ->> 'condicion', 'contado');
  v_fecha date := coalesce(nullif(p_compra ->> 'fecha', '')::date, (now() at time zone 'America/Tegucigalpa')::date);
  v_vence date;
  v_forma text := nullif(p_compra ->> 'forma_pago', '');
  v_documento text := nullif(upper(btrim(coalesce(p_compra ->> 'documento', ''))), '');
  v_turno uuid;
  v_correlativo integer;
  v_numero text;
  v_compra uuid;
  v_item jsonb;
  v_orden integer := 0;
  v_cantidad numeric;
  v_costo numeric;
  v_neto numeric;
  v_exento boolean;
  v_descripcion text;
  v_subtotal numeric := 0;
  v_exento_total numeric := 0;
  v_gravado numeric := 0;
  v_isv numeric;
  v_isv_dado numeric := nullif(p_compra ->> 'isv', '')::numeric;
begin
  if not public.tiene_rol(p_empresa, array['dueno', 'admin']) then
    raise exception 'Solo el dueño o un administrador pueden registrar compras.';
  end if;
  if v_tipo not in ('inventario', 'gasto') then
    raise exception 'Tipo de compra no válido.';
  end if;
  if v_condicion not in ('contado', 'credito') then
    raise exception 'Condición no válida.';
  end if;
  if v_fecha > (now() at time zone 'America/Tegucigalpa')::date + 1 then
    raise exception 'La fecha de la compra no puede ser futura.';
  end if;
  if jsonb_typeof(p_compra -> 'lineas') is distinct from 'array' or jsonb_array_length(p_compra -> 'lineas') = 0 then
    raise exception 'La compra no tiene líneas.';
  end if;
  if jsonb_array_length(p_compra -> 'lineas') > 300 then
    raise exception 'Máximo 300 líneas por compra.';
  end if;

  select * into v_proveedor from public.proveedores
   where id = nullif(p_compra ->> 'id_proveedor', '')::bigint and id_empresa = p_empresa;
  if not found then
    raise exception 'Elegí el proveedor.';
  end if;

  if v_documento is not null and exists (
       select 1 from public.compras c
        where c.id_empresa = p_empresa and c.id_proveedor = v_proveedor.id
          and upper(c.documento) = v_documento and c.estado = 'emitido') then
    raise exception 'La factura % de % ya está registrada.', v_documento, v_proveedor.nombre;
  end if;

  if v_condicion = 'credito' then
    v_forma := null;
    v_vence := coalesce(nullif(p_compra ->> 'vence', '')::date, v_fecha + v_proveedor.dias_credito);
    if v_vence < v_fecha then
      raise exception 'El vencimiento no puede ser antes de la fecha de la compra.';
    end if;
  else
    if v_forma is null or v_forma not in ('efectivo', 'tarjeta', 'transferencia', 'deposito', 'cheque', 'otro') then
      raise exception 'Elegí la forma de pago.';
    end if;
    -- Efectivo desde la caja: sale del turno abierto del punto de quien registra.
    if v_forma = 'efectivo' and coalesce((p_compra ->> 'de_caja')::boolean, false) then
      v_turno := public.turno_abierto((public.punto_emision_actual(p_empresa)).id);
      if v_turno is null then
        raise exception 'No hay caja abierta en tu punto: abrila o desmarcá «Sale de la caja».';
      end if;
    end if;
  end if;

  insert into public.correlativos (id_empresa, tipo) values (p_empresa, 'compra')
  on conflict (id_empresa, tipo) do nothing;
  update public.correlativos set siguiente = siguiente + 1
   where id_empresa = p_empresa and tipo = 'compra'
  returning siguiente - 1 into v_correlativo;
  v_numero := 'COMP-' || lpad(v_correlativo::text, 6, '0');

  insert into public.compras (
    id_empresa, numero, correlativo, tipo, id_proveedor, proveedor_nombre, proveedor_rtn,
    documento, cai_proveedor, fecha, condicion, vence, forma_pago, referencia_pago, notas, id_turno
  ) values (
    p_empresa, v_numero, v_correlativo, v_tipo, v_proveedor.id, v_proveedor.nombre, v_proveedor.rtn,
    v_documento, nullif(upper(btrim(coalesce(p_compra ->> 'cai', ''))), ''), v_fecha, v_condicion, v_vence, v_forma,
    case when v_forma is not null then nullif(btrim(coalesce(p_compra ->> 'referencia', '')), '') end,
    nullif(btrim(coalesce(p_compra ->> 'notas', '')), ''), v_turno
  )
  returning id into v_compra;

  -- El kardex toma el tipo y la referencia de estas variables (solo en esta transacción).
  if v_tipo = 'inventario' then
    perform set_config('wp.movimiento_tipo', 'compra', true);
    perform set_config('wp.movimiento_ref', v_numero || coalesce(' · ' || v_documento, ''), true);
  end if;

  for v_item in select * from jsonb_array_elements(p_compra -> 'lineas')
  loop
    v_orden := v_orden + 1;
    v_exento := coalesce((v_item ->> 'exento')::boolean, false);
    if v_tipo = 'inventario' then
      v_cantidad := round((v_item ->> 'cantidad')::numeric, 2);
      v_costo := round((v_item ->> 'costo')::numeric, 2);
      if v_cantidad is null or v_cantidad <= 0 then
        raise exception 'Línea %: la cantidad debe ser mayor que cero.', v_orden;
      end if;
      if v_costo is null or v_costo < 0 then
        raise exception 'Línea %: escribí el costo unitario sin ISV.', v_orden;
      end if;
      select * into v_producto from public.productos
       where id = nullif(v_item ->> 'id_producto', '')::bigint and id_empresa = p_empresa
         for update;
      if not found then
        raise exception 'Línea %: el producto no existe en tu inventario.', v_orden;
      end if;
      if not v_producto.controla_inventario then
        raise exception '«%» es un servicio: no lleva inventario.', v_producto.nombre;
      end if;
      v_neto := round(v_cantidad * v_costo, 2);
      insert into public.compras_lineas (id_compra, id_empresa, id_producto, codigo, descripcion, cantidad, costo, exento, total, orden)
      values (v_compra, p_empresa, v_producto.id, v_producto.codigo, v_producto.nombre, v_cantidad, v_costo, v_exento, v_neto, v_orden);
      -- Existencias y costo promedio ponderado (si no había existencia, manda el costo nuevo).
      update public.productos
         set existencia = existencia + v_cantidad,
             costo = case when greatest(v_producto.existencia, 0) = 0 then v_costo
                          else round((v_producto.existencia * v_producto.costo + v_cantidad * v_costo)
                                     / (v_producto.existencia + v_cantidad), 2) end
       where id = v_producto.id;
    else
      if v_item ? 'id_producto' then
        raise exception 'Línea %: una compra de gasto no lleva productos.', v_orden;
      end if;
      v_descripcion := nullif(regexp_replace(btrim(coalesce(v_item ->> 'descripcion', '')), '\s+', ' ', 'g'), '');
      v_neto := round((v_item ->> 'monto')::numeric, 2);
      if v_descripcion is null or char_length(v_descripcion) > 240 then
        raise exception 'Línea %: escribí una descripción (máximo 240 caracteres).', v_orden;
      end if;
      if v_neto is null or v_neto <= 0 or v_neto > 99999999 then
        raise exception 'Línea %: el monto debe ser mayor que cero.', v_orden;
      end if;
      insert into public.compras_lineas (id_compra, id_empresa, descripcion, cantidad, costo, exento, total, orden)
      values (v_compra, p_empresa, v_descripcion, 1, v_neto, v_exento, v_neto, v_orden);
    end if;
    v_subtotal := v_subtotal + v_neto;
    if v_exento then
      v_exento_total := v_exento_total + v_neto;
    else
      v_gravado := v_gravado + v_neto;
    end if;
  end loop;

  perform set_config('wp.movimiento_tipo', '', true);
  perform set_config('wp.movimiento_ref', '', true);

  -- ISV: el de la factura del proveedor (entre 0 y el 18 % de lo gravado) o el 15 %.
  v_isv := round(v_gravado * 0.15, 2);
  if v_isv_dado is not null then
    v_isv_dado := round(v_isv_dado, 2);
    if v_isv_dado < 0 or v_isv_dado > round(v_gravado * 0.18, 2) + 0.05 then
      raise exception 'El ISV (L %) no cuadra con lo gravado (L %).',
        to_char(v_isv_dado, 'FM999,999,990.00'), to_char(v_gravado, 'FM999,999,990.00');
    end if;
    v_isv := v_isv_dado;
  end if;

  update public.compras
     set subtotal = v_subtotal, importe_exento = v_exento_total, importe_gravado = v_gravado,
         isv = v_isv, total = v_subtotal + v_isv
   where id = v_compra;

  return v_compra;
end;
$$;

create or replace function public.anular_compra(p_compra uuid, p_motivo text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_compra public.compras;
begin
  select * into v_compra from public.compras where id = p_compra for update;
  if not found or not public.es_miembro(v_compra.id_empresa) then
    raise exception 'La compra no existe.';
  end if;
  if not public.tiene_rol(v_compra.id_empresa, array['dueno', 'admin']) then
    raise exception 'Solo el dueño o un administrador pueden anular compras.';
  end if;
  if v_compra.estado = 'anulado' then
    raise exception 'La compra ya está anulada.';
  end if;
  if nullif(btrim(p_motivo), '') is null then
    raise exception 'Escribí el motivo de la anulación.';
  end if;
  if exists (select 1 from public.pagos_proveedores_aplicaciones a
               join public.pagos_proveedores p on p.id = a.id_pago
              where a.id_compra = v_compra.id and p.estado = 'emitido') then
    raise exception 'Esta compra tiene pagos: anulá primero los pagos al proveedor.';
  end if;

  update public.compras
     set estado = 'anulado', anulado_en = now(), anulado_por = auth.uid(), motivo_anulacion = btrim(p_motivo)
   where id = p_compra;

  -- Compra de productos: las piezas vuelven a salir (el costo promedio queda como está).
  if v_compra.tipo = 'inventario' then
    perform set_config('wp.movimiento_tipo', 'anulacion', true);
    perform set_config('wp.movimiento_ref', v_compra.numero, true);
    update public.productos p
       set existencia = p.existencia - x.cantidad
      from (select id_producto, sum(cantidad) as cantidad
              from public.compras_lineas
             where id_compra = p_compra and id_producto is not null
             group by id_producto) x
     where p.id = x.id_producto;
    perform set_config('wp.movimiento_tipo', '', true);
    perform set_config('wp.movimiento_ref', '', true);
  end if;
end;
$$;

