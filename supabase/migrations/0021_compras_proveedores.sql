       p.creado_en
  from public.proveedores p;

-- Una fila por proveedor con algo pendiente.
create or replace view public.v_cuentas_proveedores with (security_invoker = true) as
select p.id,
       p.id_empresa,
       p.nombre,
       p.rtn,
       p.telefono,
       p.dias_credito,
       t.pendiente,
       coalesce(t.vencido, 0) as vencido,
       t.compras::integer as compras,
       coalesce(t.dias_mora, 0)::integer as dias_mora,
       t.proximo_vence,
       (select max(pp.fecha) from public.pagos_proveedores pp where pp.id_proveedor = p.id and pp.estado = 'emitido') as ultimo_pago,
       case when coalesce(t.vencido, 0) > 0 then 'vencida' else 'al_dia' end as estado,
       coalesce(t.vencido, 0) > 0 as en_mora
  from public.proveedores p
  join (
    select cp.id_proveedor,
           sum(cp.pendiente) as pendiente,
           sum(cp.pendiente) filter (where cp.estado = 'vencida') as vencido,
           count(*) as compras,
           max(cp.dias_vencida) as dias_mora,
           min(cp.vence) as proximo_vence
      from public.v_cuentas_pagar cp
     where cp.pendiente > 0
     group by cp.id_proveedor
  ) t on t.id_proveedor = p.id;

create or replace view public.v_compras with (security_invoker = true) as
select c.id,
       c.id_empresa,
       c.numero,
       c.tipo,
       c.fecha,
       c.id_proveedor,
       c.proveedor_nombre,
       c.proveedor_rtn,
       c.documento,
       c.condicion,
       c.vence,
       c.forma_pago,
       c.subtotal,
       c.isv,
       c.total,
       c.estado,
       cp.pendiente,
       (select count(*) from public.compras_lineas l where l.id_compra = c.id)::integer as lineas,
       u.nombre as registro,
       c.creado_en
  from public.compras c
  left join public.v_cuentas_pagar cp on cp.id = c.id
  left join public.usuarios u on u.id = c.creado_por;

create or replace view public.v_pagos_proveedores with (security_invoker = true) as
select p.id,
       p.id_empresa,
       p.numero,
       p.fecha,
       p.id_proveedor,
       p.proveedor_nombre,
       p.monto,
       p.forma_pago,
       p.referencia,
       p.notas,
       p.estado,
       p.motivo_anulacion,
       p.id_turno is not null as de_caja,
       (select string_agg(c.numero || coalesce(' (' || c.documento || ')', ''), ', ' order by c.numero)
          from public.pagos_proveedores_aplicaciones a join public.compras c on c.id = a.id_compra
         where a.id_pago = p.id) as compras,
       u.nombre as pago,
       p.creado_en
  from public.pagos_proveedores p
  left join public.usuarios u on u.id = p.creado_por;

create or replace view public.v_pagos_proveedores_aplicaciones with (security_invoker = true) as
select a.id, a.id_pago, a.id_empresa, a.id_compra, c.numero, c.documento, c.fecha as fecha_compra, c.total, a.monto
  from public.pagos_proveedores_aplicaciones a
  join public.compras c on c.id = a.id_compra;

