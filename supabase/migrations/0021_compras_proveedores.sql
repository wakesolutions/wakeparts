-- =============================================================================
-- 0021 · Compras, proveedores y cuentas por pagar
-- -----------------------------------------------------------------------------
-- ESTADO: PENDIENTE
-- Idempotente y atómica. Requiere 0018 (caja).
--
-- Qué crea o cambia:
--   · proveedores                 Por empresa: nombre, RTN, contacto, plazo de
--                                 crédito. Los administran dueño/admin.
--   · compras, compras_lineas     Factura del proveedor registrada: de
--                                 productos (suben existencias y costo promedio,
--                                 kardex «compra») o de gasto (sin inventario).
--                                 Contado o crédito. Número interno COMP-000001.
--   · pagos_proveedores,          Pagos a proveedores (PAG-000001) repartidos
--     pagos_proveedores_aplicaciones  entre sus compras al crédito.
--   · registrar_compra(), anular_compra(), registrar_pago_proveedor(),
--     anular_pago_proveedor().
--   · resumen_turno(), v_caja_movimientos   Lo pagado en efectivo desde la caja
--                                 (compras de contado y pagos) sale del turno.
--   · Vistas v_proveedores, v_compras, v_cuentas_pagar, v_cuentas_proveedores,
--     v_pagos_proveedores, v_pagos_proveedores_aplicaciones.
--
-- Reglas (docs/negocio.md §3.10):
--   · Montos sin ISV por línea; ISV 15 % sobre lo gravado (se puede corregir al
--     de la factura del proveedor, hasta el 18 %). El ISV de compras es crédito
--     fiscal (lo usa la contabilidad, 0022).
--   · Una misma factura de proveedor (proveedor + número) no se registra dos veces.
--   · Pendiente de una compra al crédito = total − pagos vigentes.
--   · Anular una compra de productos saca las existencias (el costo promedio no
--     se recalcula). No se anula con pagos vigentes.
--   · Solo dueño/admin registran o anulan compras y pagos.
-- =============================================================================

begin;

create or replace function pg_temp.restriccion_0021(tabla regclass, nombre text, definicion text)
returns void
language plpgsql
as $$
begin
  if not exists (select 1 from pg_constraint where conrelid = tabla and conname = nombre) then
    execute format('alter table %s add constraint %I %s', tabla, nombre, definicion);
  end if;
end;
$$;

