-- -----------------------------------------------------------------------------

/*
  Pago a un proveedor. p_aplicaciones null = a las compras que vencen primero;
  [{ "id_compra": "…", "monto": 500 }] = reparto elegido (debe sumar el monto).
  p_de_caja: en efectivo, sale de la caja abierta del punto de quien paga.
*/
create or replace function public.registrar_pago_proveedor(
  p_proveedor bigint,
  p_monto numeric,
  p_forma_pago text,
  p_referencia text default null,
  p_notas text default null,
  p_aplicaciones jsonb default null,
  p_de_caja boolean default false
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_proveedor public.proveedores;
  v_monto numeric := round(coalesce(p_monto, 0), 2);
  v_resto numeric;
  v_total_pendiente numeric;
  v_pago uuid;
  v_correlativo integer;
  v_compra record;
  v_item jsonb;
  v_aplicar numeric;
  v_suma numeric := 0;
  v_turno uuid;
begin
  select * into v_proveedor from public.proveedores where id = p_proveedor;
  if not found or not public.es_miembro(v_proveedor.id_empresa) then
    raise exception 'El proveedor no existe.';
  end if;
  if not public.tiene_rol(v_proveedor.id_empresa, array['dueno', 'admin']) then
    raise exception 'Solo el dueño o un administrador pueden registrar pagos a proveedores.';
  end if;
  if v_monto <= 0 then
    raise exception 'El monto debe ser mayor que cero.';
  end if;
  if p_forma_pago not in ('efectivo', 'tarjeta', 'transferencia', 'deposito', 'cheque', 'otro') then
    raise exception 'Forma de pago no válida.';
  end if;
  if p_forma_pago = 'efectivo' and coalesce(p_de_caja, false) then
    v_turno := public.turno_abierto((public.punto_emision_actual(v_proveedor.id_empresa)).id);
    if v_turno is null then
      raise exception 'No hay caja abierta en tu punto: abrila o desmarcá «Sale de la caja».';
    end if;
  end if;

  -- Bloquea las compras del proveedor: dos pagos a la vez no pagan lo mismo.
  perform 1 from public.compras c
   where c.id_proveedor = v_proveedor.id and c.condicion = 'credito' and c.estado = 'emitido'
   for update;

  select coalesce(sum(c.pendiente), 0) into v_total_pendiente
    from public.v_cuentas_pagar c where c.id_proveedor = v_proveedor.id and c.pendiente > 0;
  if v_monto > v_total_pendiente then
    raise exception 'El pago supera lo que se le debe al proveedor (L %).', to_char(v_total_pendiente, 'FM999,999,990.00');
  end if;

  insert into public.correlativos (id_empresa, tipo) values (v_proveedor.id_empresa, 'pago_proveedor')
  on conflict (id_empresa, tipo) do nothing;
  update public.correlativos set siguiente = siguiente + 1
   where id_empresa = v_proveedor.id_empresa and tipo = 'pago_proveedor'
  returning siguiente - 1 into v_correlativo;

  insert into public.pagos_proveedores (id_empresa, numero, correlativo, id_proveedor, proveedor_nombre,
                                        monto, forma_pago, referencia, notas, id_turno)
  values (v_proveedor.id_empresa, 'PAG-' || lpad(v_correlativo::text, 6, '0'), v_correlativo,
          v_proveedor.id, v_proveedor.nombre, v_monto, p_forma_pago,
          nullif(btrim(p_referencia), ''), nullif(btrim(p_notas), ''), v_turno)
  returning id into v_pago;

  if p_aplicaciones is not null and jsonb_typeof(p_aplicaciones) = 'array' and jsonb_array_length(p_aplicaciones) > 0 then
    for v_item in select * from jsonb_array_elements(p_aplicaciones)
    loop
      v_aplicar := round((v_item ->> 'monto')::numeric, 2);
      select c.* into v_compra from public.v_cuentas_pagar c
       where c.id = (v_item ->> 'id_compra')::uuid and c.id_proveedor = v_proveedor.id;
      if not found then
        raise exception 'Una de las compras no es de este proveedor o no es al crédito.';
      end if;
      if v_aplicar is null or v_aplicar <= 0 then
        continue;
      end if;
      if v_aplicar > v_compra.pendiente then
        raise exception 'A la compra % le quedan L % por pagar.', v_compra.numero,
          to_char(greatest(v_compra.pendiente, 0), 'FM999,999,990.00');
      end if;
      insert into public.pagos_proveedores_aplicaciones (id_pago, id_empresa, id_compra, monto)
      values (v_pago, v_proveedor.id_empresa, v_compra.id, v_aplicar);
      v_suma := v_suma + v_aplicar;
    end loop;
    if v_suma <> v_monto then
      raise exception 'El reparto (L %) no suma el monto del pago (L %).',
        to_char(v_suma, 'FM999,999,990.00'), to_char(v_monto, 'FM999,999,990.00');
    end if;
  else
    v_resto := v_monto;
    for v_compra in
      select c.* from public.v_cuentas_pagar c
       where c.id_proveedor = v_proveedor.id and c.pendiente > 0
       order by c.vence nulls last, c.fecha, c.numero
    loop
      exit when v_resto <= 0;
      v_aplicar := least(v_resto, v_compra.pendiente);
      insert into public.pagos_proveedores_aplicaciones (id_pago, id_empresa, id_compra, monto)
      values (v_pago, v_proveedor.id_empresa, v_compra.id, v_aplicar);
      v_resto := v_resto - v_aplicar;
    end loop;
  end if;

  return v_pago;
end;
$$;

