-- =============================================================================
-- 0005 · Ventas: clientes, CAI, carritos, cotizaciones y facturas
-- -----------------------------------------------------------------------------
-- ESTADO: YA APLICADA (2026-09-28)
-- Idempotente y atómica. Requiere 0004.
--
-- Flujo: un carrito (borrador editable, con vehículo y cliente) se convierte en
-- una COTIZACIÓN (COT-000001) o en una FACTURA con CAI (000-001-01-00000001).
-- Los documentos emitidos son inmutables: se anulan, nunca se borran.
--
-- Qué crea:
--   · empresas.descuento_maximo_vendedor   Tope de descuento para vendedores.
--   · clientes                Por empresa (RTN opcional, único por empresa).
--   · cai                     Rangos autorizados por el SAR (dueño/admin).
--   · carritos, carritos_lineas
--   · documentos, documentos_lineas        Cotizaciones y facturas emitidas.
--   · correlativos            Numeración interna por empresa (cotizaciones).
--   · emitir_documento()      Carrito → cotización o factura (numeración con
--                             bloqueo, totales en la base, descuenta existencia).
--   · anular_documento()      Anula y, si era factura, devuelve la existencia.
--   · carrito_desde_documento()  Reabre una cotización/factura como carrito.
--   · Vistas v_clientes, v_cai, v_carritos, v_carritos_lineas, v_documentos,
--     v_documentos_lineas.
--
-- Reglas fiscales usadas (ver docs/negocio.md §3.5, marcadas «a verificar»):
--   · Precios sin ISV; ISV 15 % sobre lo gravado; exento aparte.
--   · Número de factura EEE-PPP-TT-NNNNNNNN, correlativo sin huecos dentro del
--     rango del CAI; no se emite fuera de rango ni después de la fecha límite.
-- =============================================================================

begin;

create or replace function pg_temp.agregar_restriccion(tabla regclass, nombre text, definicion text)
returns void
language plpgsql
as $$
begin
  if not exists (select 1 from pg_constraint where conrelid = tabla and conname = nombre) then
    execute format('alter table %s add constraint %I %s', tabla, nombre, definicion);
  end if;
end;
$$;

