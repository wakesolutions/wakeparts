create or replace view public.v_clientes with (security_invoker = true) as
select c.id,
       c.id_empresa,
       c.nombre,
       c.rtn,
       c.telefono,
       c.correo,
       c.direccion,
       c.notas,
       c.activo,
       (select count(*) from public.documentos d where d.id_cliente = c.id and d.tipo = 'factura' and d.estado = 'emitido')::integer as facturas,
       (select max(d.fecha) from public.documentos d where d.id_cliente = c.id) as ultima_compra,
       c.creado_en
  from public.clientes c;

create or replace view public.v_cai with (security_invoker = true) as
select c.id,
       c.id_empresa,
       c.cai,
       c.tipo_documento,
       c.establecimiento,
       c.punto_emision,
       c.rango_inicial,
       c.rango_final,
       c.siguiente,
       greatest(c.rango_final - c.siguiente + 1, 0) as disponibles,
       round((c.siguiente - c.rango_inicial)::numeric / (c.rango_final - c.rango_inicial + 1) * 100, 1) as usado_pct,
       c.fecha_limite,
       (c.fecha_limite - (now() at time zone 'America/Tegucigalpa')::date) as dias_restantes,
       c.activo,
       (c.activo and c.siguiente <= c.rango_final
          and c.fecha_limite >= (now() at time zone 'America/Tegucigalpa')::date) as vigente,
       c.creado_en
  from public.cai c;

create or replace view public.v_carritos with (security_invoker = true) as
select c.id,
       c.id_empresa,
       c.nombre,
       c.id_cliente,
       c.cliente_nombre,
       c.cliente_rtn,
       c.cliente_telefono,
       c.id_marca,
       c.id_modelo,
       c.id_modelo_anio,
       c.id_especificacion,
       c.vehiculo,
       c.descuento_pct,
       c.notas,
       c.estado,
       coalesce(t.lineas, 0)::integer as lineas,
       coalesce(t.unidades, 0) as unidades,
       u.nombre as creado_por_nombre,
       c.creado_en,
       c.actualizado_en
  from public.carritos c
  left join public.usuarios u on u.id = c.creado_por
  left join (
    select id_carrito, count(*) as lineas, sum(cantidad) as unidades
      from public.carritos_lineas group by id_carrito
  ) t on t.id_carrito = c.id;

create or replace view public.v_carritos_lineas with (security_invoker = true) as
select l.id,
       l.id_carrito,
       l.id_empresa,
       l.id_producto,
       l.codigo,
       l.descripcion,
       l.cantidad,
       l.precio,
       l.descuento_pct,
       l.exento,
       l.orden,
       p.costo,
       p.existencia,
       p.controla_inventario,
       p.unidad,
       p.oem,
       (select coalesce(i.ruta_miniatura, i.ruta) from public.productos_imagenes i
         where i.id_producto = l.id_producto order by i.orden, i.id limit 1) as imagen
  from public.carritos_lineas l
  left join public.productos p on p.id = l.id_producto;

create or replace view public.v_documentos with (security_invoker = true) as
select d.id,
       d.id_empresa,
       d.tipo,
       d.numero,
       d.fecha,
       d.vence,
       d.cliente_nombre,
       d.cliente_rtn,
       d.vehiculo,
       d.subtotal,
       d.descuento,
       d.isv,
       d.total,
       d.estado,
       d.cai,
       u.nombre as vendedor,
       d.creado_en
  from public.documentos d
  left join public.usuarios u on u.id = d.creado_por;

create or replace view public.v_documentos_lineas with (security_invoker = true) as
select l.id, l.id_documento, l.id_empresa, l.id_producto, l.codigo, l.descripcion, l.cantidad,
       l.precio, l.descuento_pct, l.descuento, l.exento, l.total, l.orden
  from public.documentos_lineas l;

revoke all on public.v_clientes, public.v_cai, public.v_carritos, public.v_carritos_lineas,
