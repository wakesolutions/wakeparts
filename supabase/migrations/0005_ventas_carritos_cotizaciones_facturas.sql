  id bigint generated by default as identity primary key,
  id_empresa uuid not null references public.empresas (id) on delete cascade,
  cai text not null,
  tipo_documento text not null default '01',
  establecimiento text not null default '000',
  punto_emision text not null default '001',
  rango_inicial integer not null,
  rango_final integer not null,
  siguiente integer not null,
  fecha_limite date not null,
  activo boolean not null default true,
  creado_en timestamptz not null default now(),
  creado_por uuid references public.usuarios (id) on delete set null default auth.uid()
);

create index if not exists cai_id_empresa_idx on public.cai (id_empresa, tipo_documento, activo);
create index if not exists cai_creado_por_idx on public.cai (creado_por);
create unique index if not exists cai_codigo_key on public.cai (id_empresa, cai);

select pg_temp.agregar_restriccion('public.cai', 'cai_formato_check',
  $$check (cai ~ '^[0-9A-F]{6}-[0-9A-F]{6}-[0-9A-F]{6}-[0-9A-F]{6}-[0-9A-F]{6}-[0-9A-F]{2}$')$$);
select pg_temp.agregar_restriccion('public.cai', 'cai_codigos_check',
  $$check (tipo_documento ~ '^\d{2}$' and establecimiento ~ '^\d{3}$' and punto_emision ~ '^\d{3}$')$$);
select pg_temp.agregar_restriccion('public.cai', 'cai_rango_check',
  $$check (rango_inicial >= 1 and rango_final >= rango_inicial and rango_final <= 99999999
           and siguiente between rango_inicial and rango_final + 1)$$);

create or replace function public.tg_cai()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  v_limpio text;
begin
  if tg_op = 'INSERT' then
    v_limpio := upper(regexp_replace(coalesce(new.cai, ''), '[^0-9A-Fa-f]', '', 'g'));
    if char_length(v_limpio) = 32 then
      new.cai := substr(v_limpio, 1, 6) || '-' || substr(v_limpio, 7, 6) || '-' || substr(v_limpio, 13, 6) || '-'
              || substr(v_limpio, 19, 6) || '-' || substr(v_limpio, 25, 6) || '-' || substr(v_limpio, 31, 2);
    else
      new.cai := upper(btrim(new.cai));
    end if;
    new.establecimiento := lpad(btrim(new.establecimiento), 3, '0');
    new.punto_emision := lpad(btrim(new.punto_emision), 3, '0');
    new.tipo_documento := lpad(btrim(new.tipo_documento), 2, '0');
    new.siguiente := coalesce(new.siguiente, new.rango_inicial);
  elsif exists (select 1 from public.documentos d where d.id_cai = old.id) and (
          new.cai <> old.cai or new.establecimiento <> old.establecimiento
          or new.punto_emision <> old.punto_emision or new.tipo_documento <> old.tipo_documento
          or new.rango_inicial <> old.rango_inicial or new.rango_final <> old.rango_final
          or new.fecha_limite <> old.fecha_limite or new.id_empresa <> old.id_empresa
          or new.siguiente < old.siguiente) then
    raise exception 'Este CAI ya tiene facturas emitidas: solo se puede activar o desactivar.';
  end if;
  return new;
end;
$$;

