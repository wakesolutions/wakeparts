create or replace function public.tg_normalizar_cuenta()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if tg_op = 'UPDATE' and new.id_empresa <> old.id_empresa then
    raise exception 'No se puede cambiar la empresa de una cuenta.';
  end if;
  new.codigo := regexp_replace(coalesce(new.codigo, ''), '\D', '', 'g');
  new.nombre := regexp_replace(btrim(new.nombre), '\s+', ' ', 'g');
  new.clave := nullif(btrim(new.clave), '');
  -- Naturaleza por defecto según el tipo (se puede cambiar: depreciación acumulada, devoluciones).
  if new.naturaleza is null or btrim(new.naturaleza) = '' then
    new.naturaleza := case when new.tipo in ('activo', 'costo', 'gasto') then 'deudora' else 'acreedora' end;
  end if;
  if new.id_padre is not null then
    if new.id_padre = new.id then
      raise exception 'Una cuenta no puede ser su propia madre.';
    end if;
    if not exists (select 1 from public.cuentas_contables p where p.id = new.id_padre and p.id_empresa = new.id_empresa) then
      raise exception 'La cuenta madre no es de esta empresa.';
    end if;
    -- Sin ciclos: la madre no puede descender de esta cuenta.
    if tg_op = 'UPDATE' and exists (
         with recursive arriba as (
           select p.id, p.id_padre from public.cuentas_contables p where p.id = new.id_padre
           union all
           select c.id, c.id_padre from public.cuentas_contables c join arriba a on c.id = a.id_padre
         )
         select 1 from arriba where id = new.id) then
      raise exception 'Esa madre crearía un ciclo en el catálogo.';
    end if;
  end if;
  return new;
end;
$$;

-- La columna naturaleza se completa en el trigger: se acepta vacía al insertar.
alter table public.cuentas_contables alter column naturaleza set default '';

create or replace trigger a_normalizar
  before insert or update on public.cuentas_contables
  for each row execute function public.tg_normalizar_cuenta();

