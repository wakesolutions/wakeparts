-- Triggers: al confirmar la transacción (los documentos se insertan y luego se les ponen los totales).
create or replace function public.tg_contabilizar()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if tg_table_name = 'documentos' then
    if new.tipo not in ('factura', 'nota_credito', 'nota_debito') then
      return null;
    end if;
    if tg_op = 'INSERT' then
      perform public.contabilizar_documento(new.id);
    elsif new.estado = 'anulado' and old.estado = 'emitido' then
      perform public.revertir_origen(new.id_empresa, new.tipo, new.id::text, 'Anulación de ' || new.numero);
    end if;
  elsif tg_table_name = 'pagos' then
    if tg_op = 'INSERT' then
      perform public.contabilizar_abono(new.id);
    elsif new.estado = 'anulado' and old.estado = 'emitido' then
      perform public.revertir_origen(new.id_empresa, 'abono', new.id::text, 'Anulación del recibo ' || new.numero);
    end if;
  elsif tg_table_name = 'compras' then
    if tg_op = 'INSERT' then
      perform public.contabilizar_compra(new.id);
    elsif new.estado = 'anulado' and old.estado = 'emitido' then
      perform public.revertir_origen(new.id_empresa, 'compra', new.id::text, 'Anulación de la compra ' || new.numero);
    end if;
  elsif tg_table_name = 'pagos_proveedores' then
    if tg_op = 'INSERT' then
      perform public.contabilizar_pago_proveedor(new.id);
    elsif new.estado = 'anulado' and old.estado = 'emitido' then
      perform public.revertir_origen(new.id_empresa, 'pago_proveedor', new.id::text, 'Anulación del pago ' || new.numero);
    end if;
  elsif tg_table_name = 'cajas_movimientos' then
    perform public.contabilizar_movimiento_caja(new.id);
  elsif tg_table_name = 'cajas_turnos' then
    if new.estado = 'cerrada' and old.estado = 'abierta' then
      perform public.contabilizar_cierre_caja(new.id);
    end if;
  end if;
  return null;
end;
$$;

do $$
declare
  v_tabla text;
begin
  foreach v_tabla in array array['documentos', 'pagos', 'compras', 'pagos_proveedores'] loop
    execute format('drop trigger if exists zz_contabilizar on public.%I', v_tabla);
    execute format('create constraint trigger zz_contabilizar after insert or update of estado on public.%I '
                   'deferrable initially deferred for each row execute function public.tg_contabilizar()', v_tabla);
  end loop;
  execute 'drop trigger if exists zz_contabilizar on public.cajas_movimientos';
  execute 'create constraint trigger zz_contabilizar after insert on public.cajas_movimientos '
          'deferrable initially deferred for each row execute function public.tg_contabilizar()';
  execute 'drop trigger if exists zz_contabilizar on public.cajas_turnos';
  execute 'create constraint trigger zz_contabilizar after update of estado on public.cajas_turnos '
          'deferrable initially deferred for each row execute function public.tg_contabilizar()';
end $$;

