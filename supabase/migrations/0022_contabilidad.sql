/*
  Inserta un asiento con sus líneas (uso interno: los automáticos y crear_asiento).
  p_lineas: [{ cuenta: <clave> | <id>, debe, haber, descripcion? }]; las de
  monto cero se omiten. Devuelve el id (null si no quedó ninguna línea).
*/
create or replace function public.asentar(
  p_empresa uuid,
  p_fecha date,
  p_concepto text,
  p_origen text,
  p_id_origen text,
  p_referencia text,
  p_lineas jsonb,
  p_revierte uuid default null
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_asiento uuid;
  v_numero integer;
  v_item jsonb;
  v_cuenta bigint;
  v_debe numeric;
  v_haber numeric;
  v_orden integer := 0;
begin
  if not exists (select 1 from jsonb_array_elements(p_lineas) x
                  where round(coalesce((x ->> 'debe')::numeric, 0), 2) > 0
                     or round(coalesce((x ->> 'haber')::numeric, 0), 2) > 0) then
    return null;
  end if;

  insert into public.correlativos (id_empresa, tipo) values (p_empresa, 'asiento')
  on conflict (id_empresa, tipo) do nothing;
  update public.correlativos set siguiente = siguiente + 1
   where id_empresa = p_empresa and tipo = 'asiento'
  returning siguiente - 1 into v_numero;

  insert into public.asientos (id_empresa, numero, fecha, concepto, origen, id_origen, referencia, id_revierte)
  values (p_empresa, v_numero, p_fecha, left(btrim(p_concepto), 300), p_origen, p_id_origen, left(p_referencia, 80), p_revierte)
  returning id into v_asiento;

  for v_item in select * from jsonb_array_elements(p_lineas)
  loop
    v_debe := round(coalesce((v_item ->> 'debe')::numeric, 0), 2);
    v_haber := round(coalesce((v_item ->> 'haber')::numeric, 0), 2);
    continue when v_debe = 0 and v_haber = 0;
    -- Un monto negativo pasa al otro lado (p. ej. un costo negativo por redondeo).
    if v_debe < 0 then v_haber := v_haber - v_debe; v_debe := 0; end if;
    if v_haber < 0 then v_debe := v_debe - v_haber; v_haber := 0; end if;
    if v_debe > 0 and v_haber > 0 then
      if v_debe >= v_haber then v_debe := v_debe - v_haber; v_haber := 0;
      else v_haber := v_haber - v_debe; v_debe := 0; end if;
      continue when v_debe = 0 and v_haber = 0;
    end if;
    if jsonb_typeof(v_item -> 'cuenta') = 'number' then
      v_cuenta := (v_item ->> 'cuenta')::bigint;
    else
      v_cuenta := public.cuenta_por_clave(p_empresa, v_item ->> 'cuenta');
    end if;
    v_orden := v_orden + 1;
    insert into public.asientos_lineas (id_asiento, id_empresa, id_cuenta, debe, haber, descripcion, orden)
    values (v_asiento, p_empresa, v_cuenta, v_debe, v_haber, nullif(left(btrim(v_item ->> 'descripcion'), 200), ''), v_orden);
  end loop;

  if p_revierte is not null then
    update public.asientos set revertido_por = v_asiento where id = p_revierte;
  end if;
  return v_asiento;
end;
$$;

-- Reversa del asiento vigente de un documento (al anularlo). Fecha: hoy.
create or replace function public.revertir_origen(p_empresa uuid, p_origen text, p_id_origen text, p_concepto text)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_original public.asientos;
begin
  select * into v_original from public.asientos
   where id_empresa = p_empresa and origen = p_origen and id_origen = p_id_origen
     and id_revierte is null and revertido_por is null;
  if not found then
    return null;
  end if;
  return public.asentar(
    p_empresa, (now() at time zone 'America/Tegucigalpa')::date, p_concepto, p_origen, p_id_origen,
    v_original.referencia,
    (select jsonb_agg(jsonb_build_object('cuenta', l.id_cuenta, 'debe', l.haber, 'haber', l.debe, 'descripcion', l.descripcion)
                      order by l.orden)
       from public.asientos_lineas l where l.id_asiento = v_original.id),
    v_original.id);
end;
$$;

-- Cuenta de cobro o pago según la forma: efectivo a Caja; lo demás a Bancos.
create or replace function public.clave_forma_pago(p_forma text)
returns text
language sql
immutable
set search_path = ''
as $$
  select case when coalesce(p_forma, 'efectivo') = 'efectivo' then 'caja' else 'bancos' end;
$$;

