-- Un mes cerrado no acepta asientos.
create or replace function public.tg_periodo_abierto()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if exists (select 1 from public.periodos_cerrados p
              where p.id_empresa = new.id_empresa and p.mes = date_trunc('month', new.fecha)::date) then
    raise exception 'El mes de % está cerrado en la contabilidad: no admite asientos.',
      to_char(new.fecha, 'MM/YYYY');
  end if;
  return new;
end;
$$;

