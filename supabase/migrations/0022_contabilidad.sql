create or replace view public.v_cuentas_contables with (security_invoker = true) as
select c.id,
       c.id_empresa,
       c.codigo,
       c.nombre,
       c.tipo,
       c.naturaleza,
       c.id_padre,
       p.codigo || ' · ' || p.nombre as padre,
       c.clave,
       c.activo,
       exists (select 1 from public.cuentas_contables h where h.id_padre = c.id) as es_grupo,
       length(c.codigo) as nivel,
       c.codigo || ' · ' || c.nombre as etiqueta,
       coalesce((select sum(case when c.naturaleza = 'deudora' then l.debe - l.haber else l.haber - l.debe end)
                   from public.asientos_lineas l where l.id_cuenta = c.id), 0) as saldo,
       c.creado_en
  from public.cuentas_contables c
  left join public.cuentas_contables p on p.id = c.id_padre;

create or replace view public.v_asientos with (security_invoker = true) as
select a.id,
       a.id_empresa,
       a.numero,
       a.fecha,
       a.concepto,
       a.origen,
       a.id_origen,
       a.referencia,
       coalesce(t.debe, 0) as total,
       coalesce(t.lineas, 0)::integer as lineas,
       a.id_revierte is not null as es_reversa,
       a.revertido_por is not null as revertido,
       u.nombre as registro,
       a.creado_en
  from public.asientos a
  left join (select id_asiento, sum(debe) as debe, count(*) as lineas from public.asientos_lineas group by id_asiento) t
    on t.id_asiento = a.id
  left join public.usuarios u on u.id = a.creado_por;

create or replace view public.v_asientos_lineas with (security_invoker = true) as
select l.id, l.id_asiento, l.id_empresa, l.id_cuenta, c.codigo, c.nombre as cuenta, l.debe, l.haber, l.descripcion, l.orden
  from public.asientos_lineas l
  join public.cuentas_contables c on c.id = l.id_cuenta;

