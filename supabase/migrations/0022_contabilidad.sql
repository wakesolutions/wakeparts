-- Cada asiento cuadra: se revisa al confirmar la transacción (las líneas entran una por una).
create or replace function public.verificar_cuadre(p_asiento uuid)
returns void
language plpgsql
set search_path = ''
as $$
declare
  v_debe numeric;
  v_haber numeric;
  v_n integer;
begin
  if not exists (select 1 from public.asientos where id = p_asiento) then
    return;
  end if;
  select coalesce(sum(debe), 0), coalesce(sum(haber), 0), count(*) into v_debe, v_haber, v_n
    from public.asientos_lineas where id_asiento = p_asiento;
  if v_n < 2 then
    raise exception 'Un asiento lleva al menos dos líneas.';
  end if;
  if v_debe <> v_haber then
    raise exception 'El asiento no cuadra: debe L % y haber L %.',
      to_char(v_debe, 'FM999,999,990.00'), to_char(v_haber, 'FM999,999,990.00');
  end if;
end;
$$;

create or replace function public.tg_cuadre_asiento()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  perform public.verificar_cuadre(new.id);
  return null;
end;
$$;

create or replace function public.tg_cuadre_linea()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if tg_op = 'DELETE' then
    perform public.verificar_cuadre(old.id_asiento);
  else
    perform public.verificar_cuadre(new.id_asiento);
  end if;
  return null;
end;
$$;

