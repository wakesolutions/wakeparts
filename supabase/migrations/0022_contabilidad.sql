/*
  Asiento manual (dueño/admin). p_lineas: [{ id_cuenta, debe, haber, descripcion? }].
  Cuentas de detalle (sin subcuentas), activas y de la empresa. Debe cuadrar.
*/
create or replace function public.crear_asiento(p_empresa uuid, p_fecha date, p_concepto text, p_lineas jsonb)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_item jsonb;
  v_cuenta public.cuentas_contables;
  v_debe numeric := 0;
  v_haber numeric := 0;
  v_n integer := 0;
  v_lineas jsonb := '[]'::jsonb;
  v_d numeric;
  v_h numeric;
begin
  if not public.tiene_rol(p_empresa, array['dueno', 'admin']) then
    raise exception 'Solo el dueño o un administrador pueden registrar asientos.';
  end if;
  if nullif(btrim(p_concepto), '') is null then
    raise exception 'Escribí el concepto del asiento.';
  end if;
  if p_fecha is null or p_fecha > (now() at time zone 'America/Tegucigalpa')::date + 31 then
    raise exception 'Revisá la fecha del asiento.';
  end if;
  if jsonb_typeof(p_lineas) is distinct from 'array' or jsonb_array_length(p_lineas) > 200 then
    raise exception 'Revisá las líneas del asiento.';
  end if;
  for v_item in select * from jsonb_array_elements(p_lineas)
  loop
    v_d := round(coalesce(nullif(v_item ->> 'debe', '')::numeric, 0), 2);
    v_h := round(coalesce(nullif(v_item ->> 'haber', '')::numeric, 0), 2);
    continue when v_d = 0 and v_h = 0;
    v_n := v_n + 1;
    if v_d < 0 or v_h < 0 or (v_d > 0 and v_h > 0) then
      raise exception 'Línea %: va en el debe o en el haber, con monto positivo.', v_n;
    end if;
    select * into v_cuenta from public.cuentas_contables
     where id = nullif(v_item ->> 'id_cuenta', '')::bigint and id_empresa = p_empresa;
    if not found then
      raise exception 'Línea %: elegí la cuenta.', v_n;
    end if;
    if not v_cuenta.activo then
      raise exception 'La cuenta % % está inactiva.', v_cuenta.codigo, v_cuenta.nombre;
    end if;
    if exists (select 1 from public.cuentas_contables h where h.id_padre = v_cuenta.id) then
      raise exception '% % es una cuenta de grupo: usá una de sus subcuentas.', v_cuenta.codigo, v_cuenta.nombre;
    end if;
    v_debe := v_debe + v_d;
    v_haber := v_haber + v_h;
    v_lineas := v_lineas || jsonb_build_array(jsonb_build_object(
      'cuenta', v_cuenta.id, 'debe', v_d, 'haber', v_h, 'descripcion', v_item ->> 'descripcion'));
  end loop;
  if v_n < 2 then
    raise exception 'Un asiento lleva al menos dos líneas.';
  end if;
  if v_debe <> v_haber then
    raise exception 'No cuadra: debe L % y haber L %.', to_char(v_debe, 'FM999,999,990.00'), to_char(v_haber, 'FM999,999,990.00');
  end if;
  return public.asentar(p_empresa, p_fecha, p_concepto, 'manual', null, null, v_lineas);
end;
$$;

-- Reversa de un asiento manual (los automáticos se revierten anulando su documento).
create or replace function public.revertir_asiento(p_asiento uuid, p_motivo text)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_a public.asientos;
begin
  select * into v_a from public.asientos where id = p_asiento for update;
  if not found or not public.tiene_rol(v_a.id_empresa, array['dueno', 'admin']) then
    raise exception 'El asiento no existe.';
  end if;
  if v_a.origen not in ('manual', 'apertura_inventario') then
    raise exception 'Este asiento lo generó un documento: anulá el documento y su reversa sale sola.';
  end if;
  if v_a.id_revierte is not null then
    raise exception 'Este asiento ya es una reversa.';
  end if;
  if v_a.revertido_por is not null then
    raise exception 'Este asiento ya fue revertido.';
  end if;
  if nullif(btrim(p_motivo), '') is null then
    raise exception 'Escribí el motivo de la reversa.';
  end if;
  return public.asentar(
    v_a.id_empresa, (now() at time zone 'America/Tegucigalpa')::date,
    'Reversa del asiento ' || v_a.numero || ': ' || btrim(p_motivo), v_a.origen, null, v_a.referencia,
    (select jsonb_agg(jsonb_build_object('cuenta', l.id_cuenta, 'debe', l.haber, 'haber', l.debe, 'descripcion', l.descripcion)
                      order by l.orden)
       from public.asientos_lineas l where l.id_asiento = v_a.id),
    v_a.id);
end;
$$;

create or replace function public.cerrar_periodo(p_empresa uuid, p_mes date)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_mes date := date_trunc('month', p_mes)::date;
begin
  if not public.tiene_rol(p_empresa, array['dueno', 'admin']) then
    raise exception 'Solo el dueño o un administrador pueden cerrar meses.';
  end if;
  if v_mes >= date_trunc('month', (now() at time zone 'America/Tegucigalpa'))::date then
    raise exception 'Solo se cierran meses que ya terminaron.';
  end if;
  insert into public.periodos_cerrados (id_empresa, mes) values (p_empresa, v_mes)
  on conflict (id_empresa, mes) do nothing;
end;
$$;

create or replace function public.reabrir_periodo(p_empresa uuid, p_mes date)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not public.tiene_rol(p_empresa, array['dueno']) then
    raise exception 'Solo el dueño puede reabrir un mes cerrado.';
  end if;
  delete from public.periodos_cerrados where id_empresa = p_empresa and mes = date_trunc('month', p_mes)::date;
end;
$$;

-- Contabiliza lo emitido antes de esta migración (solo lo vigente). Devuelve cuántos asientos creó.
create or replace function public.contabilizar_pendientes(p_empresa uuid)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_n integer := 0;
  v_r record;
begin
  if not public.tiene_rol(p_empresa, array['dueno', 'admin']) then
    raise exception 'Solo el dueño o un administrador pueden contabilizar.';
  end if;
  perform public.crear_catalogo_base(p_empresa);
  for v_r in select d.id from public.documentos d
              where d.id_empresa = p_empresa and d.tipo in ('factura', 'nota_credito', 'nota_debito') and d.estado = 'emitido'
                and not exists (select 1 from public.asientos a where a.id_empresa = p_empresa and a.origen = d.tipo
                                   and a.id_origen = d.id::text)
              order by d.fecha
  loop
    if public.contabilizar_documento(v_r.id) is not null then v_n := v_n + 1; end if;
  end loop;
  for v_r in select p.id from public.pagos p
              where p.id_empresa = p_empresa and p.estado = 'emitido'
                and not exists (select 1 from public.asientos a where a.id_empresa = p_empresa and a.origen = 'abono'
                                   and a.id_origen = p.id::text)
  loop
    if public.contabilizar_abono(v_r.id) is not null then v_n := v_n + 1; end if;
  end loop;
  for v_r in select c.id from public.compras c
              where c.id_empresa = p_empresa and c.estado = 'emitido'
                and not exists (select 1 from public.asientos a where a.id_empresa = p_empresa and a.origen = 'compra'
                                   and a.id_origen = c.id::text)
  loop
    if public.contabilizar_compra(v_r.id) is not null then v_n := v_n + 1; end if;
  end loop;
  for v_r in select p.id from public.pagos_proveedores p
              where p.id_empresa = p_empresa and p.estado = 'emitido'
                and not exists (select 1 from public.asientos a where a.id_empresa = p_empresa and a.origen = 'pago_proveedor'
                                   and a.id_origen = p.id::text)
  loop
    if public.contabilizar_pago_proveedor(v_r.id) is not null then v_n := v_n + 1; end if;
  end loop;
  for v_r in select m.id from public.cajas_movimientos m
              where m.id_empresa = p_empresa
                and not exists (select 1 from public.asientos a where a.id_empresa = p_empresa
                                   and a.origen in ('caja_entrada', 'caja_salida') and a.id_origen = m.id::text)
  loop
    if public.contabilizar_movimiento_caja(v_r.id) is not null then v_n := v_n + 1; end if;
  end loop;
  for v_r in select t.id from public.cajas_turnos t
              where t.id_empresa = p_empresa and t.estado = 'cerrada' and coalesce(t.diferencia, 0) <> 0
                and not exists (select 1 from public.asientos a where a.id_empresa = p_empresa and a.origen = 'cierre_caja'
                                   and a.id_origen = t.id::text)
  loop
    if public.contabilizar_cierre_caja(v_r.id) is not null then v_n := v_n + 1; end if;
  end loop;
  return v_n;
end;
$$;

-- Asiento de apertura: el inventario que ya había (existencia × costo) contra Capital. Una sola vez.
create or replace function public.asiento_apertura_inventario(p_empresa uuid, p_fecha date)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_valor numeric;
begin
  if not public.tiene_rol(p_empresa, array['dueno', 'admin']) then
    raise exception 'Solo el dueño o un administrador pueden registrar la apertura.';
  end if;
  if exists (select 1 from public.asientos a where a.id_empresa = p_empresa and a.origen = 'apertura_inventario'
                and a.id_revierte is null and a.revertido_por is null) then
    raise exception 'La apertura del inventario ya está registrada (revertila para hacerla de nuevo).';
  end if;
  select coalesce(sum(round(p.existencia * p.costo, 2)), 0) into v_valor
    from public.productos p
   where p.id_empresa = p_empresa and p.controla_inventario and p.existencia > 0 and p.costo > 0;
  if v_valor <= 0 then
    raise exception 'No hay inventario con costo para abrir.';
  end if;
  return public.asentar(
    p_empresa, coalesce(p_fecha, (now() at time zone 'America/Tegucigalpa')::date),
    'Apertura: inventario inicial a costo', 'apertura_inventario', null, null,
    jsonb_build_array(
      jsonb_build_object('cuenta', 'inventario', 'debe', v_valor),
      jsonb_build_object('cuenta', 'capital', 'haber', v_valor)));
end;
$$;

/*
  Balanza de comprobación: por cuenta, saldo antes del período, debe, haber y
  saldo final (según su naturaleza). Incluye todas las cuentas (las de grupo
  con lo propio en cero: la suma por árbol la hace la pantalla).
*/
create or replace function public.balanza(p_empresa uuid, p_desde date, p_hasta date)
returns table (
  id bigint, codigo text, nombre text, tipo text, naturaleza text, id_padre bigint, activo boolean,
  saldo_inicial numeric, debe numeric, haber numeric, saldo_final numeric
)
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if not public.tiene_rol(p_empresa, array['dueno', 'admin']) then
    raise exception 'Solo el dueño o un administrador ven la contabilidad.';
  end if;
  return query
  with mov as (
    select l.id_cuenta,
           coalesce(sum(l.debe) filter (where a.fecha < p_desde), 0) as debe_antes,
           coalesce(sum(l.haber) filter (where a.fecha < p_desde), 0) as haber_antes,
           coalesce(sum(l.debe) filter (where a.fecha between p_desde and p_hasta), 0) as debe,
           coalesce(sum(l.haber) filter (where a.fecha between p_desde and p_hasta), 0) as haber
      from public.asientos_lineas l
      join public.asientos a on a.id = l.id_asiento
     where l.id_empresa = p_empresa and a.fecha <= p_hasta
     group by l.id_cuenta
  )
  select c.id, c.codigo, c.nombre, c.tipo, c.naturaleza, c.id_padre, c.activo,
         case when c.naturaleza = 'deudora' then coalesce(m.debe_antes - m.haber_antes, 0)
              else coalesce(m.haber_antes - m.debe_antes, 0) end,
         coalesce(m.debe, 0),
         coalesce(m.haber, 0),
         case when c.naturaleza = 'deudora'
              then coalesce(m.debe_antes - m.haber_antes + m.debe - m.haber, 0)
              else coalesce(m.haber_antes - m.debe_antes + m.haber - m.debe, 0) end
    from public.cuentas_contables c
    left join mov m on m.id_cuenta = c.id
   where c.id_empresa = p_empresa
   order by c.codigo;
end;
$$;

-- Libro mayor de una cuenta: saldo inicial y cada movimiento con su saldo corrido.
create or replace function public.mayor(p_empresa uuid, p_cuenta bigint, p_desde date, p_hasta date)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_c public.cuentas_contables;
  v_inicial numeric;
  v_signo integer;
begin
  if not public.tiene_rol(p_empresa, array['dueno', 'admin']) then
    raise exception 'Solo el dueño o un administrador ven la contabilidad.';
  end if;
  select * into v_c from public.cuentas_contables where id = p_cuenta and id_empresa = p_empresa;
  if not found then
    raise exception 'La cuenta no existe.';
  end if;
  v_signo := case when v_c.naturaleza = 'deudora' then 1 else -1 end;
  select coalesce(sum(l.debe - l.haber), 0) * v_signo into v_inicial
    from public.asientos_lineas l join public.asientos a on a.id = l.id_asiento
   where l.id_cuenta = p_cuenta and a.fecha < p_desde;
  return jsonb_build_object(
    'saldo_inicial', v_inicial,
    'movimientos', coalesce((
      select jsonb_agg(jsonb_build_object(
               'id_asiento', x.id, 'numero', x.numero, 'fecha', x.fecha, 'concepto', x.concepto,
               'referencia', x.referencia, 'descripcion', x.descripcion, 'debe', x.debe, 'haber', x.haber,
               'saldo', v_inicial + x.corrido) order by x.fecha, x.numero, x.orden)
        from (select a.id, a.numero, a.fecha, a.concepto, a.referencia, l.descripcion, l.debe, l.haber, l.orden,
                     sum((l.debe - l.haber) * v_signo) over (order by a.fecha, a.numero, l.orden) as corrido
                from public.asientos_lineas l join public.asientos a on a.id = l.id_asiento
               where l.id_cuenta = p_cuenta and a.fecha between p_desde and p_hasta) x), '[]'::jsonb));
end;
$$;

