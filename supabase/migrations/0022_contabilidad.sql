create or replace function public.contabilizar_documento(p_doc uuid)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_d public.documentos;
  v_f public.documentos;
  v_cobro text;
  v_neto numeric;
  v_costo numeric;
  v_fecha date;
  v_nombre text;
begin
  select * into v_d from public.documentos where id = p_doc;
  if not found or v_d.tipo not in ('factura', 'nota_credito', 'nota_debito') then
    return null;
  end if;
  if exists (select 1 from public.asientos a
              where a.id_empresa = v_d.id_empresa and a.origen = v_d.tipo and a.id_origen = v_d.id::text
                and a.id_revierte is null) then
    return null;
  end if;

  v_fecha := (v_d.fecha at time zone 'America/Tegucigalpa')::date;
  v_neto := v_d.total - v_d.isv;
  select coalesce(sum(round(l.cantidad * coalesce(l.costo, 0), 2)), 0) into v_costo
    from public.documentos_lineas l
   where l.id_documento = v_d.id and l.controla_inventario and l.id_producto is not null and l.costo is not null;

  if v_d.tipo = 'factura' then
    v_cobro := case when v_d.condicion = 'credito' then 'clientes' else public.clave_forma_pago(v_d.forma_pago) end;
  elsif v_d.id_factura is not null then
    select * into v_f from public.documentos where id = v_d.id_factura;
    v_cobro := case when v_f.condicion = 'credito' then 'clientes' else public.clave_forma_pago(v_f.forma_pago) end;
  else
    -- Nota sin factura (0019): su forma de pago; sin dinero, queda contra el cliente.
    v_cobro := case when v_d.forma_pago is null then 'clientes' else public.clave_forma_pago(v_d.forma_pago) end;
  end if;

  v_nombre := case v_d.tipo when 'factura' then 'Venta' when 'nota_credito' then 'Nota de crédito' else 'Nota de débito' end;

  return public.asentar(
    v_d.id_empresa, v_fecha,
    v_nombre || ' ' || v_d.numero || ' · ' || v_d.cliente_nombre,
    v_d.tipo, v_d.id::text, v_d.numero,
    case v_d.tipo
      when 'factura' then jsonb_build_array(
        jsonb_build_object('cuenta', v_cobro, 'debe', v_d.total),
        jsonb_build_object('cuenta', 'ventas', 'haber', v_neto),
        jsonb_build_object('cuenta', 'isv_debito', 'haber', v_d.isv),
        jsonb_build_object('cuenta', 'costo_ventas', 'debe', v_costo, 'descripcion', 'Costo de lo vendido'),
        jsonb_build_object('cuenta', 'inventario', 'haber', v_costo, 'descripcion', 'Salida de inventario'))
      when 'nota_credito' then jsonb_build_array(
        jsonb_build_object('cuenta', 'devoluciones_ventas', 'debe', v_neto),
        jsonb_build_object('cuenta', 'isv_debito', 'debe', v_d.isv),
        jsonb_build_object('cuenta', v_cobro, 'haber', v_d.total),
        jsonb_build_object('cuenta', 'inventario', 'debe', case when v_d.reintegra_inventario then v_costo else 0 end,
                           'descripcion', 'Piezas que regresan'),
        jsonb_build_object('cuenta', 'costo_ventas', 'haber', case when v_d.reintegra_inventario then v_costo else 0 end,
                           'descripcion', 'Costo de lo devuelto'))
      else jsonb_build_array(
        jsonb_build_object('cuenta', v_cobro, 'debe', v_d.total),
        jsonb_build_object('cuenta', 'otros_ingresos', 'haber', v_neto),
        jsonb_build_object('cuenta', 'isv_debito', 'haber', v_d.isv))
    end);
end;
$$;

