-- Cuenta que usa el sistema para una clave (precarga el catálogo si falta).
create or replace function public.cuenta_por_clave(p_empresa uuid, p_clave text)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_id bigint;
begin
  select id into v_id from public.cuentas_contables where id_empresa = p_empresa and clave = p_clave;
  if v_id is null then
    perform public.crear_catalogo_base(p_empresa);
    select id into v_id from public.cuentas_contables where id_empresa = p_empresa and clave = p_clave;
  end if;
  if v_id is null then
    raise exception 'Falta la cuenta contable «%» en el catálogo (Contabilidad › Catálogo).', p_clave;
  end if;
  return v_id;
end;
$$;

