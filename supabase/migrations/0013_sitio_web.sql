-- -----------------------------------------------------------------------------
-- 5. Enviar un pedido (anónimo)
-- -----------------------------------------------------------------------------

create or replace function public.enviar_pedido_web(
  p_slug text,
  p_cliente jsonb,
  p_vehiculo jsonb,
  p_lineas jsonb
)
returns jsonb
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_empresa uuid := public.empresa_sitio(p_slug);
  v_headers jsonb := coalesce(nullif(current_setting('request.headers', true), ''), '{}')::jsonb;
  v_ip inet := public.ip_segura(v_headers ->> 'x-cliente-ip');
  v_nombre text := left(btrim(coalesce(p_cliente ->> 'nombre', '')), 120);
  v_telefono text := regexp_replace(coalesce(p_cliente ->> 'telefono', ''), '\D', '', 'g');
  v_correo text := nullif(left(btrim(coalesce(p_cliente ->> 'correo', '')), 120), '');
  v_mensaje text := nullif(left(btrim(coalesce(p_cliente ->> 'mensaje', '')), 600), '');
  v_marca integer;
  v_modelo integer;
  v_anio integer;
  v_esp integer;
  v_vehiculo text;
  v_pedido public.pedidos_web;
  v_linea jsonb;
  v_orden integer := 0;
  v_validas integer := 0;
begin
  if v_empresa is null then
    raise exception 'Este catálogo no está disponible.' using errcode = 'P0001';
  end if;
  if char_length(v_nombre) < 2 then
    raise exception 'Escribí tu nombre.' using errcode = 'P0001';
  end if;
  if v_telefono !~ '^[0-9]{8,15}$' then
    raise exception 'Escribí un teléfono de 8 dígitos.' using errcode = 'P0001';
  end if;
  if v_correo is not null and v_correo !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' then
    raise exception 'El correo no es válido.' using errcode = 'P0001';
  end if;
  if jsonb_typeof(p_lineas) <> 'array' or jsonb_array_length(p_lineas) = 0 then
    raise exception 'Tu lista está vacía.' using errcode = 'P0001';
  end if;
  if jsonb_array_length(p_lineas) > 40 then
    raise exception 'Son demasiadas piezas para un pedido web. Llamanos.' using errcode = 'P0001';
  end if;

  -- Límite anti abuso: 6 pedidos por hora por IP y 3 cada 10 minutos por teléfono.
  if v_ip is not null and (select count(*) from public.pedidos_web
                            where ip = v_ip and creado_en > now() - interval '1 hour') >= 6 then
    raise exception 'Mandaste varios pedidos seguidos. Esperá un rato o llamanos.' using errcode = 'P0001';
  end if;
  if (select count(*) from public.pedidos_web
       where cliente_telefono = v_telefono and creado_en > now() - interval '10 minutes') >= 3 then
    raise exception 'Ya recibimos tus pedidos. Te vamos a contactar pronto.' using errcode = 'P0001';
  end if;

  -- Vehículo: solo ids que existen y son coherentes entre sí.
  if jsonb_typeof(p_vehiculo) = 'object' then
    select ma.id into v_marca from public.marcas ma where ma.id = (p_vehiculo ->> 'id_marca')::integer;
    if v_marca is not null then
      select mo.id into v_modelo from public.modelos mo
       where mo.id = (p_vehiculo ->> 'id_modelo')::integer and mo.id_marca = v_marca;
    end if;
    if v_modelo is not null then
      select ya.id into v_anio from public.modelos_anios ya
       where ya.id = (p_vehiculo ->> 'id_modelo_anio')::integer and ya.id_modelo = v_modelo;
    end if;
    if v_anio is not null then
      select e.id into v_esp from public.especificaciones e
       where e.id = (p_vehiculo ->> 'id_especificacion')::integer and e.id_modelo_anio = v_anio;
    end if;
    select concat_ws(' ', ma.marca, mo.modelo, ya.anio::text,
                     case when e.id is not null then round(e.motor_cc / 1000.0, 1)::text || ' L' end)
      into v_vehiculo
      from public.marcas ma
      left join public.modelos mo on mo.id = v_modelo
      left join public.modelos_anios ya on ya.id = v_anio
      left join public.especificaciones e on e.id = v_esp
     where ma.id = v_marca;
  end if;

  insert into public.pedidos_web (id_empresa, cliente_nombre, cliente_telefono, cliente_correo, mensaje,
                                  id_marca, id_modelo, id_modelo_anio, id_especificacion, vehiculo, ip)
  values (v_empresa, v_nombre, v_telefono, v_correo, v_mensaje, v_marca, v_modelo, v_anio, v_esp,
          left(v_vehiculo, 200), v_ip)
  returning * into v_pedido;

  -- Las líneas toman nombre, código y precio de la base: nunca del navegador.
  for v_linea in select * from jsonb_array_elements(p_lineas) loop
    insert into public.pedidos_web_lineas (id_pedido, id_empresa, id_producto, codigo, descripcion, cantidad,
                                           precio, exento, orden)
    select v_pedido.id, v_empresa, p.id, p.codigo, p.nombre,
           least(greatest(round(coalesce((v_linea ->> 'cantidad')::numeric, 1), 0), 1), 999),
           p.precio, p.exento, v_orden
      from public.productos p
     where p.id = (v_linea ->> 'id_producto')::bigint
       and p.id_empresa = v_empresa and p.activo and p.visible_catalogo;
    if found then
      v_validas := v_validas + 1;
      v_orden := v_orden + 1;
    end if;
  end loop;

  if v_validas = 0 then
    raise exception 'Las piezas de tu lista ya no están disponibles.' using errcode = 'P0001';
  end if;

  return jsonb_build_object('id', v_pedido.id, 'numero', v_pedido.numero, 'lineas', v_validas);
exception
  when invalid_text_representation or numeric_value_out_of_range then
    raise exception 'Datos no válidos.' using errcode = 'P0001';
end;
$$;

-- -----------------------------------------------------------------------------
-- 6. Atender un pedido: se vuelve un carrito del mostrador
-- -----------------------------------------------------------------------------

create or replace function public.atender_pedido_web(p_pedido uuid)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_pedido public.pedidos_web;
  v_carrito uuid;
begin
  select * into v_pedido from public.pedidos_web where id = p_pedido for update;
  if not found or not public.es_miembro(v_pedido.id_empresa) then
    raise exception 'El pedido no existe.' using errcode = 'P0001';
  end if;

  -- Ya atendido y su carrito sigue abierto: se reabre ese.
  if v_pedido.id_carrito is not null
     and exists (select 1 from public.carritos c where c.id = v_pedido.id_carrito and c.estado = 'abierto') then
    return v_pedido.id_carrito;
  end if;

  insert into public.carritos (id_empresa, nombre, cliente_nombre, cliente_telefono,
                               id_marca, id_modelo, id_modelo_anio, id_especificacion, notas)
  values (v_pedido.id_empresa, 'Web #' || v_pedido.numero, v_pedido.cliente_nombre, v_pedido.cliente_telefono,
          v_pedido.id_marca, v_pedido.id_modelo, v_pedido.id_modelo_anio, v_pedido.id_especificacion,
          left(concat_ws(E'\n', 'Pedido web #' || v_pedido.numero, v_pedido.mensaje), 1000))
  returning id into v_carrito;

  -- Precio de hoy (el del pedido es referencia: pudo cambiar).
  insert into public.carritos_lineas (id_carrito, id_empresa, id_producto, codigo, descripcion, cantidad, precio,
                                      exento, orden)
  select v_carrito, v_pedido.id_empresa, l.id_producto, coalesce(p.codigo, l.codigo), coalesce(p.nombre, l.descripcion),
         l.cantidad, coalesce(p.precio, l.precio), coalesce(p.exento, l.exento), l.orden
    from public.pedidos_web_lineas l
    left join public.productos p on p.id = l.id_producto
   where l.id_pedido = p_pedido
   order by l.orden;

  update public.pedidos_web
     set estado = 'atendido', id_carrito = v_carrito, atendido_por = auth.uid(), atendido_en = now()
   where id = p_pedido;

  return v_carrito;
end;
$$;

