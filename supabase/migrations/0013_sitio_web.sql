-- Empresa de un slug si el sitio se puede ver (publicado, o el usuario es miembro).
create or replace function public.empresa_sitio(p_slug text)
returns uuid
language sql
stable
security definer
set search_path = ''
as $$
  select e.id
    from public.empresas e
   where e.slug = lower(btrim(p_slug))
     and e.activo
     and (e.sitio_publicado or public.es_miembro(e.id));
$$;

-- ¿El taller muestra precios en su sitio?
create or replace function public.sitio_muestra_precios(p_empresa uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce((e.sitio ->> 'mostrarPrecios')::boolean, true)
    from public.empresas e where e.id = p_empresa;
$$;

revoke all on function public.empresa_sitio(text), public.sitio_muestra_precios(uuid) from public, anon, authenticated;

