-- =============================================================================
-- 0013 · Sitio web público de cada empresa (catálogo + pedidos web)
-- -----------------------------------------------------------------------------
-- Cada taller puede publicar su sitio en /t/<slug>: portada, catálogo con
-- búsqueda por vehículo, ficha de producto, «Nosotros» y un carrito que llega
-- al sistema como PEDIDO WEB. El vendedor lo atiende y se vuelve un carrito del
-- mostrador (de ahí, cotización o factura como siempre).
--
--   · empresas.slug              Dirección pública (/t/<slug>), única.
--   · empresas.sitio_publicado   ¿Se ve sin sesión? (los miembros siempre ven
--                                la vista previa).
--   · empresas.sitio             Configuración (jsonb): textos de portada y
--                                Nosotros, WhatsApp, horario, destacados,
--                                mostrar precios… La normaliza la app
--                                (lib/sitio-web.ts).
--   · pedidos_web(+_lineas)      Lo que mandan los visitantes. Solo se crean con
--                                enviar_pedido_web() (anónimo, validado y con
--                                límite por IP/teléfono).
--   · Funciones públicas         sitio_publico, portada_web,
--                                buscar_catalogo_web, producto_web: solo
--                                productos visibles con existencia y SIN costo;
--                                el precio sale null si el taller lo oculta.
--   · buscar_productos()         Deja de ser anónima: el público entra por
--                                buscar_catalogo_web (que respeta «ocultar
--                                precios»).
--   · atender_pedido_web()       Pedido → carrito del mostrador.
--
-- ESTADO: YA APLICADA (confirmado 2026-10-02)
-- Idempotente y transaccional: se puede ejecutar más de una vez.
-- =============================================================================

begin;

-- Otras migraciones crean una igual en la misma sesión: se reemplaza.
drop function if exists pg_temp.agregar_restriccion(regclass, text, text);
create function pg_temp.agregar_restriccion(p_tabla regclass, p_nombre text, p_def text)
returns void
language plpgsql
as $$
begin
  if not exists (select 1 from pg_constraint where conrelid = p_tabla and conname = p_nombre) then
    execute format('alter table %s add constraint %I %s', p_tabla, p_nombre, p_def);
  end if;
end;
$$;

