-- Portada: destacados (los elegidos por el taller o, si no hay, los últimos con
-- foto) y categorías con productos visibles.
create or replace function public.portada_web(p_slug text)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_empresa uuid := public.empresa_sitio(p_slug);
  v_precios boolean;
  v_elegidos bigint[];
  v_destacados jsonb;
  v_categorias jsonb;
begin
  if v_empresa is null then
    return null;
  end if;
  v_precios := public.sitio_muestra_precios(v_empresa);
  select coalesce(array_agg(d.valor::bigint), '{}')
    into v_elegidos
    from public.empresas e,
         jsonb_array_elements_text(coalesce(e.sitio -> 'destacados', '[]'::jsonb)) as d(valor)
   where e.id = v_empresa and d.valor ~ '^\d{1,18}$';

  with visibles as (
    select p.*
      from public.productos p
     where p.id_empresa = v_empresa and p.activo and p.visible_catalogo
       and (not p.controla_inventario or p.existencia > 0)
  ), elegidos as (
    select v.*, coalesce(array_position(v_elegidos, v.id), 1000) as pos
      from visibles v
     where cardinality(v_elegidos) = 0 or v.id = any (v_elegidos)
  )
  select coalesce(jsonb_agg(jsonb_build_object(
           'id', x.id, 'codigo', x.codigo, 'nombre', x.nombre,
           'marca', mp.nombre, 'categoria', c.nombre, 'condicion', x.condicion,
           'precio', case when v_precios then x.precio end, 'exento', x.exento,
           'imagen', (select coalesce(i.ruta_miniatura, i.ruta) from public.productos_imagenes i
                       where i.id_producto = x.id order by i.orden, i.id limit 1))
           order by x.pos, x.creado_en desc), '[]'::jsonb)
    into v_destacados
    from (
      select * from elegidos e
       order by e.pos,
                exists (select 1 from public.productos_imagenes i where i.id_producto = e.id) desc,
                e.creado_en desc
       limit 8
    ) x
    left join public.marcas_productos mp on mp.id = x.id_marca_producto
    join public.categorias c on c.id = x.id_categoria;

  select coalesce(jsonb_agg(jsonb_build_object('id', t.id, 'nombre', t.nombre, 'productos', t.n)
           order by t.n desc, t.nombre), '[]'::jsonb)
    into v_categorias
    from (
      select c.id, c.nombre, count(*) as n
        from public.productos p
        join public.categorias c on c.id = p.id_categoria
       where p.id_empresa = v_empresa and p.activo and p.visible_catalogo
         and (not p.controla_inventario or p.existencia > 0)
       group by c.id, c.nombre
       order by n desc
       limit 12
    ) t;

  return jsonb_build_object('destacados', v_destacados, 'categorias', v_categorias);
end;
$$;

-- Búsqueda pública: la misma de mostrador (buscar_productos), pero solo lo
-- visible con existencia, sin costo ni ubicación, y sin precio si el taller lo oculta.
create or replace function public.buscar_catalogo_web(
  p_slug text,
  p_texto text default '',
  p_id_marca integer default null,
  p_id_modelo integer default null,
  p_id_modelo_anio integer default null,
  p_id_especificacion integer default null,
  p_id_categoria integer default null,
  p_limite integer default 48
)
returns table (
  id bigint,
  codigo text,
  nombre text,
  marca text,
  id_categoria integer,
  categoria text,
  condicion text,
  unidad text,
  precio numeric,
  exento boolean,
  imagen text,
  grupo text,
  ajuste text
)
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_empresa uuid := public.empresa_sitio(p_slug);
  v_precios boolean;
begin
  if v_empresa is null then
    return;
  end if;
  v_precios := public.sitio_muestra_precios(v_empresa);
  return query
  select b.id, b.codigo, b.nombre, b.marca, b.id_categoria, b.categoria, b.condicion, b.unidad,
         case when v_precios then b.precio end, b.exento, b.imagen, b.grupo, b.ajuste
    from public.buscar_productos(v_empresa, p_texto, p_id_marca, p_id_modelo, p_id_modelo_anio,
                                 p_id_especificacion, p_id_categoria, least(coalesce(p_limite, 48), 96)) b
    join public.productos p on p.id = b.id
   where p.visible_catalogo and p.activo and (not p.controla_inventario or p.existencia > 0)
   order by b.orden;
end;
$$;

-- Ficha pública de un producto: datos, fotos y vehículos a los que le queda.
create or replace function public.producto_web(p_slug text, p_producto bigint)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_empresa uuid := public.empresa_sitio(p_slug);
  v_resultado jsonb;
begin
  if v_empresa is null then
    return null;
  end if;
  select jsonb_build_object(
           'id', p.id, 'codigo', p.codigo, 'nombre', p.nombre, 'descripcion', p.descripcion,
           'marca', mp.nombre, 'id_categoria', p.id_categoria, 'categoria', c.nombre,
           'oem', p.oem, 'numero_parte', p.numero_parte, 'condicion', p.condicion,
           'unidad', p.unidad, 'garantia_dias', p.garantia_dias,
           'precio', case when public.sitio_muestra_precios(v_empresa) then p.precio end,
           'exento', p.exento,
           'imagenes', coalesce((select jsonb_agg(jsonb_build_object('ruta', i.ruta, 'miniatura', i.ruta_miniatura)
                                                  order by i.orden, i.id)
                                   from public.productos_imagenes i where i.id_producto = p.id), '[]'::jsonb),
           'vehiculos', coalesce((select jsonb_agg(v.texto order by v.texto)
                                    from (select distinct concat_ws(' ', ma.marca, mo.modelo, ya.anio::text,
                                                   case when e.id is not null then
                                                     round(e.motor_cc / 1000.0, 1)::text || ' L' end) as texto
                                            from public.productos_compatibilidades k
                                            join public.marcas ma on ma.id = k.id_marca
                                            left join public.modelos mo on mo.id = k.id_modelo
                                            left join public.modelos_anios ya on ya.id = k.id_modelo_anio
                                            left join public.especificaciones e on e.id = k.id_especificacion
                                           where k.id_producto = p.id
                                           limit 80) v), '[]'::jsonb)
         )
    into v_resultado
    from public.productos p
    join public.categorias c on c.id = p.id_categoria
    left join public.marcas_productos mp on mp.id = p.id_marca_producto
   where p.id = p_producto and p.id_empresa = v_empresa and p.activo and p.visible_catalogo
     and (not p.controla_inventario or p.existencia > 0);
  return v_resultado;
end;
$$;

