-- Mantiene el par inverso: A ↔ B.
create or replace function public.tg_categorias_relacionadas_simetria()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' then
    insert into public.categorias_relacionadas (id_categoria, id_relacionada, motivo)
    values (new.id_relacionada, new.id_categoria, new.motivo)
    on conflict (id_categoria, id_relacionada) do nothing;
    return new;
  elsif tg_op = 'UPDATE' then
    update public.categorias_relacionadas
       set motivo = new.motivo
     where id_categoria = new.id_relacionada and id_relacionada = new.id_categoria
       and motivo is distinct from new.motivo;
    return new;
  else
    delete from public.categorias_relacionadas
     where id_categoria = old.id_relacionada and id_relacionada = old.id_categoria;
    return old;
  end if;
end;
$$;

create or replace trigger z_simetria
  after insert or update or delete on public.categorias_relacionadas
  for each row execute function public.tg_categorias_relacionadas_simetria();

