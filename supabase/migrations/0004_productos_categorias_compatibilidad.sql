create or replace function public.tg_productos_imagenes()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  select p.id_empresa into new.id_empresa from public.productos p where p.id = new.id_producto;
  if new.id_empresa is null then
    raise exception 'El producto no existe.';
  end if;
  if new.ruta not like new.id_empresa::text || '/' || new.id_producto::text || '/%'
     or (new.ruta_miniatura is not null
         and new.ruta_miniatura not like new.id_empresa::text || '/' || new.id_producto::text || '/%') then
    raise exception 'Ruta de imagen no válida.';
  end if;
  return new;
end;
$$;

