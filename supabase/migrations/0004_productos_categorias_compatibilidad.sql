-- -----------------------------------------------------------------------------
-- 7. Compatibilidad producto ↔ vehículo
--    Se guarda el nivel más específico elegido y el trigger completa los
--    ancestros: una fila de año lleva marca, modelo y año; una de marca, solo
--    la marca. Así «le queda a este vehículo» es una comparación directa.
-- -----------------------------------------------------------------------------

create table if not exists public.productos_compatibilidades (
  id bigint generated by default as identity primary key,
  id_empresa uuid not null references public.empresas (id) on delete cascade,
  id_producto bigint not null references public.productos (id) on delete cascade,
  id_marca integer not null references public.marcas (id) on delete cascade,
  id_modelo integer references public.modelos (id) on delete cascade,
  id_modelo_anio integer references public.modelos_anios (id) on delete cascade,
  id_especificacion integer references public.especificaciones (id) on delete cascade,
  nivel smallint generated always as (
    case
      when id_especificacion is not null then 4
      when id_modelo_anio is not null then 3
      when id_modelo is not null then 2
      else 1
    end
  ) stored,
  nota text,
  creado_en timestamptz not null default now(),
  creado_por uuid references public.usuarios (id) on delete set null default auth.uid(),
  constraint productos_compatibilidades_key
    unique nulls not distinct (id_producto, id_marca, id_modelo, id_modelo_anio, id_especificacion)
);

create index if not exists productos_compat_vehiculo_idx
  on public.productos_compatibilidades (id_empresa, id_marca, id_modelo, id_modelo_anio);
create index if not exists productos_compat_id_modelo_idx on public.productos_compatibilidades (id_modelo);
create index if not exists productos_compat_id_modelo_anio_idx on public.productos_compatibilidades (id_modelo_anio);
create index if not exists productos_compat_id_especificacion_idx on public.productos_compatibilidades (id_especificacion);
create index if not exists productos_compat_creado_por_idx on public.productos_compatibilidades (creado_por);

create or replace function public.tg_compatibilidades_completar()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.id_especificacion is not null then
    select e.id_modelo_anio into new.id_modelo_anio from public.especificaciones e where e.id = new.id_especificacion;
  end if;
  if new.id_modelo_anio is not null then
    select ya.id_modelo into new.id_modelo from public.modelos_anios ya where ya.id = new.id_modelo_anio;
  end if;
  if new.id_modelo is not null then
    select mo.id_marca into new.id_marca from public.modelos mo where mo.id = new.id_modelo;
  end if;
  select p.id_empresa into new.id_empresa from public.productos p where p.id = new.id_producto;
  new.nota := nullif(btrim(new.nota), '');
  return new;
end;
$$;

create or replace trigger a_completar
  before insert or update on public.productos_compatibilidades
  for each row execute function public.tg_compatibilidades_completar();

-- Quita filas cubiertas por otra más general del mismo producto
-- (si el producto sirve para todo COROLLA, sobran las filas de COROLLA 2005).
create or replace function public.compactar_compatibilidades(p_producto bigint)
returns integer
language sql
set search_path = ''
as $$
  with borradas as (
    delete from public.productos_compatibilidades c
     where c.id_producto = p_producto
       and exists (
         select 1 from public.productos_compatibilidades g
          where g.id_producto = c.id_producto
            and g.nivel < c.nivel
            and g.id_marca = c.id_marca
            and (g.id_modelo is null or g.id_modelo = c.id_modelo)
            and (g.id_modelo_anio is null or g.id_modelo_anio = c.id_modelo_anio)
       )
    returning 1
  )
  select count(*)::integer from borradas;
$$;

-- Asigna o quita en bloque. p_nivel: marca | modelo | anio | especificacion.
-- Devuelve cuántas filas cambiaron. Respeta RLS (dueño/admin de la empresa).
create or replace function public.asignar_compatibilidades(
  p_producto bigint,
  p_nivel text,
  p_ids integer[],
  p_asignar boolean default true
)
returns integer
language plpgsql
set search_path = ''
as $$
declare
  v_n integer := 0;
begin
  if p_nivel not in ('marca', 'modelo', 'anio', 'especificacion') then
    raise exception 'Nivel de compatibilidad no válido.';
  end if;
  if coalesce(cardinality(p_ids), 0) = 0 then
    return 0;
  end if;
  if cardinality(p_ids) > 2000 then
    raise exception 'Demasiados vehículos en una sola operación.';
  end if;

  if p_asignar then
    insert into public.productos_compatibilidades (id_producto, id_marca, id_modelo, id_modelo_anio, id_especificacion)
    select p_producto,
           case when p_nivel = 'marca' then x end,
           case when p_nivel = 'modelo' then x end,
           case when p_nivel = 'anio' then x end,
           case when p_nivel = 'especificacion' then x end
      from unnest(p_ids) as x
    on conflict do nothing;
    get diagnostics v_n = row_count;
    perform public.compactar_compatibilidades(p_producto);
  else
    delete from public.productos_compatibilidades
     where id_producto = p_producto
       and case p_nivel
             when 'marca' then nivel = 1 and id_marca = any (p_ids)
             when 'modelo' then nivel = 2 and id_modelo = any (p_ids)
             when 'anio' then nivel = 3 and id_modelo_anio = any (p_ids)
             else nivel = 4 and id_especificacion = any (p_ids)
           end;
    get diagnostics v_n = row_count;
  end if;
  return v_n;
end;
$$;

-- Copia la compatibilidad de otro producto de la misma empresa.
create or replace function public.copiar_compatibilidades(p_origen bigint, p_destino bigint)
returns integer
language plpgsql
set search_path = ''
as $$
declare
  v_n integer;
begin
  if (select id_empresa from public.productos where id = p_origen)
     is distinct from (select id_empresa from public.productos where id = p_destino) then
    raise exception 'Solo se puede copiar entre productos de la misma empresa.';
  end if;
  insert into public.productos_compatibilidades (id_producto, id_marca, id_modelo, id_modelo_anio, id_especificacion, nota)
  select p_destino, id_marca, id_modelo, id_modelo_anio, id_especificacion, nota
    from public.productos_compatibilidades
   where id_producto = p_origen
  on conflict do nothing;
  get diagnostics v_n = row_count;
  perform public.compactar_compatibilidades(p_destino);
  return v_n;
end;
$$;

