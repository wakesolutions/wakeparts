-- Normaliza, genera el código si viene vacío y arma el texto de búsqueda.
create or replace function public.tg_productos_preparar()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  v_servicio boolean;
  v_marca text;
  v_ref text;
  v_codigos text[] := '{}';
begin
  if tg_op = 'UPDATE' and new.id_empresa <> old.id_empresa then
    raise exception 'No se puede cambiar la empresa de un producto.';
  end if;

  new.nombre := regexp_replace(btrim(new.nombre), '\s+', ' ', 'g');
  new.codigo := upper(btrim(coalesce(new.codigo, '')));
  if new.codigo = '' then
    new.codigo := 'P-' || lpad(new.id::text, 6, '0');
  end if;
  new.descripcion := nullif(btrim(new.descripcion), '');
  new.oem := nullif(upper(btrim(new.oem)), '');
  new.numero_parte := nullif(upper(btrim(new.numero_parte)), '');
  new.codigo_barras := nullif(btrim(new.codigo_barras), '');
  new.referencias := nullif(upper(btrim(new.referencias)), '');
  new.ubicacion := nullif(upper(btrim(new.ubicacion)), '');
  new.notas := nullif(btrim(new.notas), '');

  select c.es_servicio into v_servicio from public.categorias c where c.id = new.id_categoria;
  if coalesce(v_servicio, false) then
    new.controla_inventario := false;
    new.unidad := 'servicio';
  end if;
  if not new.controla_inventario then
    new.existencia := 0;
    new.existencia_minima := 0;
  end if;

  select m.nombre into v_marca from public.marcas_productos m where m.id = new.id_marca_producto;

  v_codigos := array[
    public.wp_codigo(new.codigo), public.wp_codigo(new.oem),
    public.wp_codigo(new.numero_parte), public.wp_codigo(new.codigo_barras)
  ];
  foreach v_ref in array regexp_split_to_array(coalesce(new.referencias, ''), '[,;/\s]+') loop
    v_codigos := v_codigos || public.wp_codigo(v_ref);
  end loop;
  new.codigos := ' ' || array_to_string(array(select distinct c from unnest(v_codigos) c where c <> ''), ' ') || ' ';

  new.texto_busqueda := public.wp_fonetico(concat_ws(' ',
    new.nombre, new.descripcion, v_marca, public.categoria_texto(new.id_categoria),
    new.codigo, new.oem, new.numero_parte, new.referencias,
    case new.condicion when 'usado' then 'usado' when 'reconstruido' then 'reconstruido' end
  )) || new.codigos;

  new.actualizado_en := now();
  return new;
end;
$$;

create or replace trigger a_preparar
  before insert or update on public.productos
  for each row execute function public.tg_productos_preparar();

-- Si cambia el nombre o los sinónimos de una categoría o marca, se rehace el
-- texto de búsqueda de sus productos (de todas las empresas).
create or replace function public.tg_refrescar_busqueda_productos()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if tg_table_name = 'categorias' then
    update public.productos set texto_busqueda = texto_busqueda
     where id_categoria in (select public.categorias_subarbol(new.id));
  else
    update public.productos set texto_busqueda = texto_busqueda
     where id_marca_producto = new.id;
  end if;
  return null;
end;
$$;

create or replace trigger z_refrescar_productos
  after update of nombre, sinonimos, id_padre on public.categorias
  for each row
  when (old.nombre is distinct from new.nombre or old.sinonimos is distinct from new.sinonimos
        or old.id_padre is distinct from new.id_padre)
  execute function public.tg_refrescar_busqueda_productos();

create or replace trigger z_refrescar_productos
  after update of nombre on public.marcas_productos
  for each row
  when (old.nombre is distinct from new.nombre)
  execute function public.tg_refrescar_busqueda_productos();

