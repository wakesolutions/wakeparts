-- Normaliza, genera el slug, hereda «es servicio» y evita ciclos / más de 3 niveles.
create or replace function public.tg_categorias_arbol()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  v_nivel integer := 1;
  v_actual integer := new.id_padre;
  v_base text;
  v_n integer := 1;
begin
  new.nombre := regexp_replace(btrim(new.nombre), '\s+', ' ', 'g');
  new.descripcion := nullif(btrim(new.descripcion), '');
  new.sinonimos := nullif(regexp_replace(lower(btrim(new.sinonimos)), '\s*,\s*', ', ', 'g'), '');

  if new.slug is null or btrim(new.slug) = '' then
    v_base := btrim(regexp_replace(public.wp_normalizar(new.nombre), '[^a-z0-9]+', '-', 'g'), '-');
    v_base := left(coalesce(nullif(v_base, ''), 'categoria'), 70);
    new.slug := v_base;
    while exists (select 1 from public.categorias where slug = new.slug and id is distinct from new.id) loop
      v_n := v_n + 1;
      new.slug := v_base || '-' || v_n;
    end loop;
  end if;

  while v_actual is not null loop
    if v_actual = new.id then
      raise exception 'Una categoría no puede estar dentro de sí misma.';
    end if;
    v_nivel := v_nivel + 1;
    if v_nivel > 3 then
      raise exception 'El árbol de categorías admite como máximo 3 niveles.';
    end if;
    select c.id_padre into v_actual from public.categorias c where c.id = v_actual;
  end loop;

  if new.id_padre is not null then
    select c.es_servicio into new.es_servicio from public.categorias c where c.id = new.id_padre;
  end if;
  return new;
end;
$$;

create or replace trigger a_arbol
  before insert or update on public.categorias
  for each row execute function public.tg_categorias_arbol();

-- Ruta legible y texto de búsqueda de una categoría (incluye ancestros y sinónimos).
create or replace function public.categoria_texto(p_categoria integer)
returns text
language sql
stable
set search_path = ''
as $$
  with recursive sube as (
    select id, id_padre, nombre, sinonimos, 1 as paso from public.categorias where id = p_categoria
    union all
    select c.id, c.id_padre, c.nombre, c.sinonimos, s.paso + 1
      from public.categorias c join sube s on c.id = s.id_padre
  )
  select string_agg(concat_ws(' ', nombre, sinonimos), ' ' order by paso) from sube;
$$;

-- Ids de una categoría y todas sus descendientes.
create or replace function public.categorias_subarbol(p_categoria integer)
returns setof integer
language sql
stable
set search_path = ''
as $$
  with recursive baja as (
    select id from public.categorias where id = p_categoria
    union all
    select c.id from public.categorias c join baja b on c.id_padre = b.id
  )
  select id from baja;
$$;

