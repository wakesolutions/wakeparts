-- 10. Búsqueda de vehículos: «corolla 05», «hilux 2010», «nissan fron»
-- -----------------------------------------------------------------------------

create or replace function public.buscar_vehiculos(p_texto text, p_limite integer default 20)
returns table (
  id_marca integer,
  marca text,
  id_modelo integer,
  modelo text,
  id_modelo_anio integer,
  anio integer,
  anio_desde integer,
  anio_hasta integer
)
language plpgsql
stable
set search_path = public, extensions
as $$
#variable_conflict use_column
declare
  v_tokens text[] := array(
    select t from unnest(regexp_split_to_array(public.wp_normalizar(left(coalesce(p_texto, ''), 80)), '[^a-z0-9]+')) t
     where t <> ''
  );
  v_palabras text[] := '{}';
  v_anio integer;
  v_i integer;
begin
  for v_i in 1 .. coalesce(cardinality(v_tokens), 0) loop
    if v_tokens[v_i] ~ '^(19|20)[0-9]{2}$' then
      v_anio := v_tokens[v_i]::integer;
    elsif v_tokens[v_i] ~ '^[0-9]{2}$' and v_i = cardinality(v_tokens) and v_i > 1 then
      -- «corolla 05» → 2005 · «civic 98» → 1998
      v_anio := case when v_tokens[v_i]::integer >= 50 then 1900 else 2000 end + v_tokens[v_i]::integer;
    else
      v_palabras := v_palabras || v_tokens[v_i];
    end if;
  end loop;

  if cardinality(v_palabras) = 0 then
    return;
  end if;

  return query
  with candidatos as (
    select mo.id_marca, mo.marca::text as marca, mo.id as id_modelo, mo.modelo::text as modelo,
           mo.anio_desde, mo.anio_hasta, mo.anios,
           public.wp_normalizar(mo.marca || ' ' || mo.modelo) as texto,
           public.wp_codigo(mo.marca || mo.modelo) as junto,
           public.wp_normalizar(mo.modelo) as solo_modelo
      from public.v_modelos mo
  )
  select c.id_marca, c.marca, c.id_modelo, c.modelo, ya.id, ya.anio, c.anio_desde, c.anio_hasta
    from candidatos c
    left join public.modelos_anios ya on v_anio is not null and ya.id_modelo = c.id_modelo and ya.anio = v_anio
   where (v_anio is null or ya.id is not null)
     and not exists (
       select 1 from unnest(v_palabras) w
        where not (c.texto like '%' || w || '%' or c.junto like '%' || w || '%')
     )
   order by
     case
       when c.solo_modelo = array_to_string(v_palabras, ' ') then 0
       when c.solo_modelo like v_palabras[1] || '%' then 1
       when c.texto like v_palabras[1] || '%' then 2
       else 3
     end,
     c.marca, c.modelo
   limit least(greatest(coalesce(p_limite, 20), 1), 50);
end;
$$;

grant execute on function public.buscar_vehiculos(text, integer) to anon, authenticated;

