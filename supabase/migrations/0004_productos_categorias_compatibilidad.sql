  $$check (tipo in ('inicial', 'ajuste', 'venta', 'anulacion', 'compra', 'devolucion'))$$);

-- Todo cambio de existencia deja un movimiento. Quien cambia la existencia por
-- una operación (p. ej. facturar) define antes, dentro de la transacción:
--   set_config('wp.movimiento_tipo', 'venta', true)
--   set_config('wp.movimiento_ref', '000-001-01-00000001', true)
create or replace function public.tg_productos_kardex()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_anterior numeric := case when tg_op = 'INSERT' then 0 else old.existencia end;
begin
  if new.existencia = v_anterior then
    return null;
  end if;
  insert into public.movimientos_inventario (id_empresa, id_producto, tipo, cantidad, existencia, costo, referencia)
  values (
    new.id_empresa, new.id,
    coalesce(nullif(current_setting('wp.movimiento_tipo', true), ''),
             case when tg_op = 'INSERT' then 'inicial' else 'ajuste' end),
    new.existencia - v_anterior,
    new.existencia,
    new.costo,
    nullif(current_setting('wp.movimiento_ref', true), '')
  );
  return null;
end;
$$;

create or replace trigger z_kardex
  after insert or update of existencia on public.productos
  for each row execute function public.tg_productos_kardex();

