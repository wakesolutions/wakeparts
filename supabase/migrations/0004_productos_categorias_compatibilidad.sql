  before insert or update on public.productos_imagenes
  for each row execute function public.tg_productos_imagenes();

-- Empresa dueña de un archivo según su carpeta (null si la ruta no es válida).
create or replace function public.empresa_de_ruta(p_ruta text)
returns uuid
language sql
immutable
set search_path = ''
as $$
  select case
    when split_part(p_ruta, '/', 1) ~ '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
      then split_part(p_ruta, '/', 1)::uuid
  end;
$$;

