-- Minúsculas y sin tildes: base de toda comparación de búsqueda.
create or replace function public.wp_normalizar(valor text)
returns text
language sql
immutable
parallel safe
set search_path = public, extensions
as $$
  select lower(unaccent('unaccent'::regdictionary, coalesce(valor, '')));
$$;

-- Forma «de oído» para tolerar faltas comunes de mostrador: ll→y, v→b,
-- z/ce/ci→s, h muda, que/qui→ke/ki. Se aplica igual al texto guardado y a lo
-- que se busca («pastiyas» encuentra «pastillas», «balinera» y «valinera»).
create or replace function public.wp_fonetico(valor text)
returns text
language sql
immutable
parallel safe
set search_path = public, extensions
as $f$
  select regexp_replace(regexp_replace(regexp_replace(regexp_replace(regexp_replace(
           public.wp_normalizar(valor),
           'll', 'y', 'g'),
           'v', 'b', 'g'),
           'z|c(?=[ei])', 's', 'g'),
           '(^|[^c])h', '\1', 'g'),
           'qu(?=[ei])', 'k', 'g');
$f$;

-- Códigos comparables: solo letras y números («04465-02220» → «0446502220»).
create or replace function public.wp_codigo(valor text)
returns text
language sql
immutable
parallel safe
set search_path = ''
as $$
  select lower(regexp_replace(coalesce(valor, ''), '[^0-9A-Za-z]', '', 'g'));
$$;

create or replace function pg_temp.agregar_restriccion(tabla regclass, nombre text, definicion text)
returns void
language plpgsql
as $$
begin
  if not exists (select 1 from pg_constraint where conrelid = tabla and conname = nombre) then
    execute format('alter table %s add constraint %I %s', tabla, nombre, definicion);
  end if;
end;
$$;

