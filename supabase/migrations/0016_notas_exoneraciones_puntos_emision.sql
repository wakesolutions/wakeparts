create or replace view public.v_puntos_emision with (security_invoker = true) as
select p.id,
       p.id_empresa,
       p.establecimiento || '-' || p.punto_emision as codigo,
       p.establecimiento,
       p.sucursal,
       p.punto_emision,
       p.nombre,
       p.establecimiento || '-' || p.punto_emision || ' · ' || p.nombre as etiqueta,
       p.direccion,
       p.telefono,
       p.predeterminado,
       p.activo,
       (select count(*) from public.empresas_usuarios eu
         where eu.id_punto_emision = p.id and eu.activo)::integer as usuarios,
       (select count(*) from public.cai c
         where c.id_punto_emision = p.id and c.activo and c.siguiente <= c.rango_final
           and c.fecha_limite >= (now() at time zone 'America/Tegucigalpa')::date)::integer as cai_vigentes,
       p.creado_en
  from public.puntos_emision p;

create or replace view public.v_cai with (security_invoker = true) as
select c.id,
       c.id_empresa,
       c.cai,
       c.tipo_documento,
       c.establecimiento,
       c.punto_emision,
       c.rango_inicial,
       c.rango_final,
       c.siguiente,
       greatest(c.rango_final - c.siguiente + 1, 0) as disponibles,
       round((c.siguiente - c.rango_inicial)::numeric / (c.rango_final - c.rango_inicial + 1) * 100, 1) as usado_pct,
       c.fecha_limite,
       (c.fecha_limite - (now() at time zone 'America/Tegucigalpa')::date) as dias_restantes,
       c.activo,
       (c.activo and c.siguiente <= c.rango_final
          and c.fecha_limite >= (now() at time zone 'America/Tegucigalpa')::date) as vigente,
       c.creado_en,
       c.id_punto_emision,
       p.nombre as punto
  from public.cai c
  left join public.puntos_emision p on p.id = c.id_punto_emision;

