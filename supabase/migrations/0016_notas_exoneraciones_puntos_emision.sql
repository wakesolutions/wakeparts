create or replace function public.tg_cai()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  v_limpio text;
  v_punto public.puntos_emision;
begin
  if tg_op = 'INSERT' then
    v_limpio := upper(regexp_replace(coalesce(new.cai, ''), '[^0-9A-Fa-f]', '', 'g'));
    if char_length(v_limpio) = 32 then
      new.cai := substr(v_limpio, 1, 6) || '-' || substr(v_limpio, 7, 6) || '-' || substr(v_limpio, 13, 6) || '-'
              || substr(v_limpio, 19, 6) || '-' || substr(v_limpio, 25, 6) || '-' || substr(v_limpio, 31, 2);
    else
      new.cai := upper(btrim(new.cai));
    end if;
    new.tipo_documento := lpad(btrim(new.tipo_documento), 2, '0');
    new.siguiente := coalesce(new.siguiente, new.rango_inicial);
  elsif exists (select 1 from public.documentos d where d.id_cai = old.id) and (
          new.cai <> old.cai or new.tipo_documento <> old.tipo_documento
          or new.id_punto_emision is distinct from old.id_punto_emision
          or new.rango_inicial <> old.rango_inicial or new.rango_final <> old.rango_final
          or new.fecha_limite <> old.fecha_limite or new.id_empresa <> old.id_empresa
          or new.siguiente < old.siguiente) then
    raise exception 'Este CAI ya tiene documentos emitidos: solo se puede activar o desactivar.';
  end if;

  -- Punto de emisión: el elegido manda; si vienen solo los códigos, se busca o se crea.
  if new.id_punto_emision is not null then
    select * into v_punto from public.puntos_emision
     where id = new.id_punto_emision and id_empresa = new.id_empresa;
    if not found then
      raise exception 'El punto de emisión no existe.';
    end if;
  else
    new.establecimiento := lpad(btrim(coalesce(new.establecimiento, '000')), 3, '0');
    new.punto_emision := lpad(btrim(coalesce(new.punto_emision, '001')), 3, '0');
    select * into v_punto from public.puntos_emision
     where id_empresa = new.id_empresa and establecimiento = new.establecimiento
       and punto_emision = new.punto_emision;
    if not found then
      insert into public.puntos_emision (id_empresa, establecimiento, punto_emision)
      values (new.id_empresa, new.establecimiento, new.punto_emision)
      returning * into v_punto;
    end if;
  end if;
  new.id_punto_emision := v_punto.id;
  new.establecimiento := v_punto.establecimiento;
  new.punto_emision := v_punto.punto_emision;
  return new;
end;
$$;

grant update (id_punto_emision) on public.cai to authenticated;

