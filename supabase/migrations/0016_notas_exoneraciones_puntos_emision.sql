-- =============================================================================
-- 0016 · Notas de crédito y débito, devoluciones, exoneraciones y puntos de emisión
-- -----------------------------------------------------------------------------
-- ESTADO: PENDIENTE
-- Idempotente y atómica. Requiere 0005 (ventas) y 0003 (membresías). Usa 0011
-- (auditoría) si existe.
--
-- Qué crea o cambia:
--   · puntos_emision          Establecimientos (sucursales) y puntos de emisión
--                             (cajas) por empresa; uno es el predeterminado.
--                             Se crean solos desde los CAI ya registrados.
--   · cai.id_punto_emision    Cada CAI pertenece a un punto de emisión.
--   · empresas_usuarios.id_punto_emision
--                             Punto de emisión de cada persona (null = el
--                             predeterminado). Cada quien puede elegir el suyo.
--   · clientes / carritos     Datos de exoneración (constancia de registro de
--                             exonerado, orden de compra exenta, registro SAG).
--   · documentos              Tipos nota_credito y nota_debito; referencia a la
--                             factura que modifican; motivo; importe exonerado;
--                             punto de emisión; devolución con reintegro.
--   · documentos_lineas.id_linea_origen   Línea de la factura que se acredita.
--   · emitir_documento()      Numera con el CAI del punto de emisión de quien
--                             factura y aplica la exoneración.
--   · emitir_nota()           Nota de crédito (devolución, descuento, corrección)
--                             o de débito sobre una factura emitida.
--   · anular_documento()      No anula facturas con notas vigentes; al anular
--                             una devolución vuelve a sacar las existencias.
--   · Vistas v_puntos_emision, v_lineas_acreditables; columnas nuevas al final
--     de v_cai, v_miembros, v_carritos, v_documentos, v_documentos_lineas,
--     v_clientes.
--
-- Reglas fiscales (docs/negocio.md §3.5):
--   · Tipo de documento SAR: 01 factura, 06 nota de crédito, 07 nota de débito.
--   · Factura exonerada: exige RTN del cliente y la orden de compra exenta o la
--     constancia de registro de exonerado; lo gravado pasa a «importe exonerado»
--     y no lleva ISV.
--   · Una nota no puede acreditar más de lo que queda de la factura (total +
--     débitos − créditos), ni devolver más unidades de las vendidas.
-- =============================================================================

begin;

create or replace function pg_temp.restriccion_0016(tabla regclass, nombre text, definicion text)
returns void
language plpgsql
as $$
begin
  if not exists (select 1 from pg_constraint where conrelid = tabla and conname = nombre) then
    execute format('alter table %s add constraint %I %s', tabla, nombre, definicion);
  end if;
end;
$$;

