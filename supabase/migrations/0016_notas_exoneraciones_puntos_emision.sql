create policy empresas_usuarios_propio_punto on public.empresas_usuarios
  for update to authenticated
  using (id_usuario = auth.uid() and activo)
  with check (id_usuario = auth.uid() and activo);

-- Punto de emisión con el que emite quien llama: el suyo (si está activo) o el predeterminado.
create or replace function public.punto_emision_actual(p_empresa uuid)
returns public.puntos_emision
language sql
stable
security definer
set search_path = ''
as $$
  select p.*
    from public.puntos_emision p
   where p.id_empresa = p_empresa and p.activo and public.es_miembro(p_empresa)
   order by (p.id = (select eu.id_punto_emision from public.empresas_usuarios eu
                      where eu.id_empresa = p_empresa and eu.id_usuario = auth.uid())) desc nulls last,
            p.predeterminado desc, p.id
   limit 1;
$$;

revoke all on function public.punto_emision_actual(uuid) from public, anon;
grant execute on function public.punto_emision_actual(uuid) to authenticated;

