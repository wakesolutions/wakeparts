-- Igual que en 0003, pero el punto de emisión no es un cambio de rol: cada quien
-- elige el suyo y dueño/admin se lo asignan a cualquiera.
create or replace function public.tg_reglas_membresia()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor uuid := auth.uid();
begin
  if new.id_punto_emision is not null
     and new.id_punto_emision is distinct from old.id_punto_emision
     and not exists (select 1 from public.puntos_emision p
                      where p.id = new.id_punto_emision and p.id_empresa = new.id_empresa and p.activo) then
    raise exception 'El punto de emisión no existe o está inactivo.';
  end if;

  -- Cambios hechos por el sistema (SQL/migraciones) no se restringen.
  if v_actor is null or (new.rol, new.activo) is not distinct from (old.rol, old.activo) then
    return new;
  end if;

  if old.id_usuario = v_actor then
    raise exception 'No podés cambiar tu propio rol ni desactivarte.';
  end if;

  if (old.rol = 'dueno' or new.rol = 'dueno')
     and not public.tiene_rol(old.id_empresa, array['dueno']) then
    raise exception 'Solo un dueño puede modificar a otro dueño o asignar ese rol.';
  end if;

  if old.rol = 'dueno' and old.activo and (new.rol <> 'dueno' or not new.activo)
     and not exists (
       select 1 from public.empresas_usuarios
        where id_empresa = old.id_empresa and rol = 'dueno' and activo
          and id_usuario <> old.id_usuario
     ) then
    raise exception 'La empresa debe tener al menos un dueño activo.';
  end if;

  return new;
end;
$$;

-- La política de 0003 solo deja editar a dueño/admin; cada quien puede tocar su
-- propia fila (el trigger y el permiso por columna limitan qué).
