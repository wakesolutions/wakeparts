create or replace function public.tg_puntos_emision()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if tg_op = 'UPDATE' and new.id_empresa <> old.id_empresa then
    raise exception 'No se puede cambiar la empresa de un punto de emisión.';
  end if;
  new.establecimiento := lpad(btrim(new.establecimiento), 3, '0');
  new.punto_emision := lpad(btrim(new.punto_emision), 3, '0');
  new.sucursal := regexp_replace(btrim(new.sucursal), '\s+', ' ', 'g');
  new.nombre := regexp_replace(btrim(new.nombre), '\s+', ' ', 'g');
  new.direccion := nullif(btrim(new.direccion), '');
  new.telefono := nullif(btrim(new.telefono), '');

  if tg_op = 'UPDATE'
     and (new.establecimiento <> old.establecimiento or new.punto_emision <> old.punto_emision)
     and exists (select 1 from public.cai c where c.id_punto_emision = old.id) then
    raise exception 'Este punto ya tiene CAI registrados: sus códigos no se pueden cambiar. Creá otro punto.';
  end if;

  -- El primero de la empresa es el predeterminado; marcar uno desmarca los demás
  -- (ese update interno se marca para no volver a entrar en esta regla).
  if coalesce(current_setting('wp.desmarcando_punto', true), '') <> 'si' then
    if not exists (select 1 from public.puntos_emision p
                    where p.id_empresa = new.id_empresa and p.predeterminado and p.id <> new.id) then
      new.predeterminado := true;
    elsif new.predeterminado then
      perform set_config('wp.desmarcando_punto', 'si', true);
      update public.puntos_emision set predeterminado = false
       where id_empresa = new.id_empresa and predeterminado and id <> new.id;
      perform set_config('wp.desmarcando_punto', '', true);
    end if;
  end if;
  if new.predeterminado and not new.activo then
    raise exception 'El punto predeterminado no se puede desactivar. Marcá otro como predeterminado primero.';
  end if;
  return new;
end;
$$;

create or replace trigger a_preparar
  before insert or update on public.puntos_emision
  for each row execute function public.tg_puntos_emision();

