-- 0005 + datos de exoneración del cliente elegido.
create or replace function public.tg_carritos()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  v_tope numeric;
  v_cli record;
begin
  if tg_op = 'UPDATE' and new.id_empresa <> old.id_empresa then
    raise exception 'No se puede cambiar la empresa de un carrito.';
  end if;
  if tg_op = 'UPDATE' and old.estado = 'cerrado' and new.estado = 'cerrado' then
    raise exception 'Este carrito ya se cerró. Abrí uno nuevo.';
  end if;

  -- Cliente elegido: copia sus datos (y su exoneración) si no se escribieron otros.
  if new.id_cliente is not null
     and (tg_op = 'INSERT' or new.id_cliente is distinct from old.id_cliente) then
    select c.nombre, c.rtn, c.telefono, c.exonerado, c.exo_constancia, c.exo_registro_sag into v_cli
      from public.clientes c where c.id = new.id_cliente and c.id_empresa = new.id_empresa;
    if not found then
      raise exception 'El cliente no existe.';
    end if;
    new.cliente_nombre := v_cli.nombre;
    new.cliente_rtn := v_cli.rtn;
    new.cliente_telefono := v_cli.telefono;
    new.exonerado := v_cli.exonerado;
    new.exo_constancia := v_cli.exo_constancia;
    new.exo_registro_sag := v_cli.exo_registro_sag;
    new.exo_orden_compra := null;
  end if;

  new.nombre := nullif(btrim(new.nombre), '');
  new.cliente_nombre := nullif(upper(regexp_replace(btrim(new.cliente_nombre), '\s+', ' ', 'g')), '');
  new.cliente_rtn := nullif(regexp_replace(coalesce(new.cliente_rtn, ''), '\D', '', 'g'), '');
  new.cliente_telefono := nullif(btrim(new.cliente_telefono), '');
  new.notas := nullif(btrim(new.notas), '');
  new.exo_orden_compra := nullif(upper(btrim(new.exo_orden_compra)), '');
  new.exo_constancia := nullif(upper(btrim(new.exo_constancia)), '');
  new.exo_registro_sag := nullif(upper(btrim(new.exo_registro_sag)), '');

  -- Vehículo: completa ancestros y arma el texto «TOYOTA COROLLA 2005 · 1.8 L».
  if new.id_especificacion is not null then
    select e.id_modelo_anio into new.id_modelo_anio from public.especificaciones e where e.id = new.id_especificacion;
  end if;
  if new.id_modelo_anio is not null then
    select ya.id_modelo into new.id_modelo from public.modelos_anios ya where ya.id = new.id_modelo_anio;
  end if;
  if new.id_modelo is not null then
    select mo.id_marca into new.id_marca from public.modelos mo where mo.id = new.id_modelo;
  end if;
  select nullif(concat_ws(' ', ma.marca, mo.modelo, ya.anio::text,
                          case when e.id is not null then '· ' || round(e.motor_cc / 1000.0, 1)::text || ' L'
                               || coalesce(' ' || e.motor_numero, '') end), '')
    into new.vehiculo
    from (select 1) x
    left join public.marcas ma on ma.id = new.id_marca
    left join public.modelos mo on mo.id = new.id_modelo
    left join public.modelos_anios ya on ya.id = new.id_modelo_anio
    left join public.especificaciones e on e.id = new.id_especificacion;

  if new.descuento_pct > 0
     and (tg_op = 'INSERT' or new.descuento_pct <> old.descuento_pct)
     and auth.uid() is not null
     and coalesce(current_setting('wp.copia_documento', true), '') <> 'si'
     and not public.tiene_rol(new.id_empresa, array['dueno', 'admin']) then
    select e.descuento_maximo_vendedor into v_tope from public.empresas e where e.id = new.id_empresa;
    if new.descuento_pct > v_tope then
      raise exception 'Tu rol permite hasta % %% de descuento.', rtrim(to_char(v_tope, 'FM990.##'), '.');
    end if;
  end if;

  new.actualizado_en := now();
  return new;
end;
$$;

