  from public.documentos_lineas l;

-- Líneas de una factura con lo ya devuelto en notas de crédito emitidas.
create or replace view public.v_lineas_acreditables with (security_invoker = true) as
select l.id,
       l.id_documento,
       l.id_empresa,
       l.id_producto,
       l.codigo,
       l.descripcion,
       l.cantidad,
       l.precio,
       l.descuento_pct,
       l.exento,
       l.total,
       l.controla_inventario,
       l.orden,
       coalesce(n.devuelto, 0) as devuelto,
       coalesce(n.acreditado, 0) as acreditado
  from public.documentos_lineas l
  left join (
    select nl.id_linea_origen, sum(nl.cantidad) as devuelto, sum(nl.total) as acreditado
      from public.documentos_lineas nl
      join public.documentos nd on nd.id = nl.id_documento
     where nd.tipo = 'nota_credito' and nd.estado = 'emitido' and nl.id_linea_origen is not null
     group by nl.id_linea_origen
  ) n on n.id_linea_origen = l.id;

revoke all on public.v_puntos_emision, public.v_lineas_acreditables from anon;
grant select on public.v_puntos_emision, public.v_lineas_acreditables to authenticated;

